    zeros(nRows,nMethod);


CountTest = ...
    zeros(nRows,nMethod);


MeanTrain = ...
    nan(nRows,nMethod);


MeanTest = ...
    nan(nRows,nMethod);


MaxTrain = ...
    nan(nRows,nMethod);


