%% ========================================================================
% 8. CALCULATE TABLE STATISTICS
%
% ORIGINAL UNCAPPED VARIANCE IS USED.
% ========================================================================

row = ...
    0;


for ib = 1:nBlock

    CaseName = ...
        BlockCase{ib};


    CaseLabel = ...
        BlockCaseLabel{ib};


    Regime = ...
        BlockRegime{ib};


    assert( ...
        isfield(SpatialVariance,CaseName), ...
        'Missing case: %s', ...
        CaseName);


    assert( ...
        isfield(SpatialVariance.(CaseName),Regime), ...
        'Missing regime: %s %s', ...
        CaseName, ...
        Regime);


    DataTrain = ...
        SpatialVariance. ...
        (CaseName). ...
        (Regime). ...
        Train;


    DataTest = ...
        SpatialVariance. ...
        (CaseName). ...
        (Regime). ...
        Test;


    for i = 1:nModel

        row = ...
            row + 1;


        CaseRegimeColumn(row) = ...
            string( ...
                [CaseLabel '; ' Regime]);


        CaseColumn(row) = ...
            string(CaseLabel);


        RegimeColumn(row) = ...
            string(Regime);


        EGMColumn(row) = ...
            string(Model_Name{i});


        for j = 1:nMethod

            runName = ...
                [ListOfModel{i} '_' ListFunction{j}];


            %% ============================================================
            % TRAIN
            % =============================================================

            assert( ...
                isfield(DataTrain,runName), ...
                'Missing Train run: %s %s %s', ...
                CaseName, ...
                Regime, ...
                runName);


            assert( ...
                isfield(DataTrain.(runName),'Variance'), ...
                'Missing Train Variance field: %s', ...
                runName);


            V = ...
                DataTrain.(runName).Variance(:);


            assert( ...
                ~isempty(V), ...
                'Empty Train variance: %s', ...
                runName);


            assert( ...
                all(isfinite(V)), ...
                'Train variance contains NaN/Inf: %s', ...
                runName);


            assert( ...
                all(V >= -NegativeTolerance), ...
                'Negative Train variance detected: %s', ...
                runName);


            % Correct only tiny machine-precision negative values.
            V( ...
                V < 0 & ...
                V >= -NegativeTolerance) = ...
                0;


            idx = ...
                V > Threshold;


            CountTrain(row,j) = ...
                nnz(idx);


            if any(idx)

                MeanTrain(row,j) = ...
                    mean(V(idx));


                MaxTrain(row,j) = ...
                    max(V(idx));

            end


            %% ============================================================
            % TEST
            % =============================================================

            assert( ...
                isfield(DataTest,runName), ...
                'Missing Test run: %s %s %s', ...
                CaseName, ...
                Regime, ...
                runName);


            assert( ...
                isfield(DataTest.(runName),'Variance'), ...
                'Missing Test Variance field: %s', ...
                runName);


            V = ...
                DataTest.(runName).Variance(:);


            assert( ...
                ~isempty(V), ...
                'Empty Test variance: %s', ...
                runName);


            assert( ...
                all(isfinite(V)), ...
                'Test variance contains NaN/Inf: %s', ...
                runName);


            assert( ...
                all(V >= -NegativeTolerance), ...
                'Negative Test variance detected: %s', ...
                runName);


            V( ...
                V < 0 & ...
                V >= -NegativeTolerance) = ...
                0;


            idx = ...
                V > Threshold;


            CountTest(row,j) = ...
                nnz(idx);


            if any(idx)

                MeanTest(row,j) = ...
                    mean(V(idx));


                MaxTest(row,j) = ...
                    max(V(idx));

            end

        end

    end

end


assert( ...
    row == nRows, ...
    'Unexpected number of table rows.');


