%% ========================================================================
% Create manuscript Tables C7--C9 from the FINAL spatial-variance dataset.
%
% Input:
%   Current_SpatialVariance_Calibrated.mat
%
% Data field:
%   .Variance
%
% IMPORTANT:
%   - RBF values are FINAL calibrated variances.
%   - Kriging values are predictive variances.
%   - Original UNCAPPED variance is used for all statistics.
%   - Figure capping at 0.05 m^2 has NO effect on these tables.
%
% Threshold:
%   Variance > 0.05 m^2
%
% Table 4:
%   Number of locations with variance > 0.05 m^2
%
% Table 5:
%   Mean variance among locations with variance > 0.05 m^2
%
% Table 6:
%   Maximum variance among locations with variance > 0.05 m^2
%
% Current EGMs:
%   E08, GGP, EC4, GCO, SG2, X19
%
% Methods:
%   G, M, T, C, L, S
%
% Outputs:
%   SpatialVariance_Above_0p05.xlsx
%   SpatialVariance_Tables.tex
%
% Normal successful execution:
%   No Command Window messages.
%
% Errors/assertions remain active.
% ========================================================================

clear
clc

%% Collect Spatial Variance

Collect_SpatialVariance
%% ========================================================================
% 1. USER INPUT
% ========================================================================

RootDir = '.';


InputFile = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'SpatialVariance', ...
        'Current_SpatialVariance_Calibrated.mat');


OutputDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'Manuscript');


ExcelFile = ...
    fullfile( ...
        OutputDir, ...
        'SpatialVariance_Above_0p05.xlsx');


LatexFile = ...
    fullfile( ...
        OutputDir, ...
        'SpatialVariance_Tables.tex');


if ~isfolder(OutputDir)

    mkdir(OutputDir);

end


