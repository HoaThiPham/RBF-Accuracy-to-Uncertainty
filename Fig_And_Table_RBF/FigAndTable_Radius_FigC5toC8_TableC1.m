        'textbox', ...
        Fmt.Title.Position, ...
        'String', ...
        Fmt.Title.String, ...
        'EdgeColor', ...
        'none', ...
        'HorizontalAlignment', ...
        Fmt.Title.HorizontalAlignment, ...
        'VerticalAlignment', ...
        Fmt.Title.VerticalAlignment, ...
        'FontSize', ...
        Fmt.Font.TitleSize, ...
        'FontName', ...
        Fmt.Font.Name, ...
        'FontWeight', ...
        Fmt.Title.FontWeight, ...
        'Interpreter', ...
        'none');

end


