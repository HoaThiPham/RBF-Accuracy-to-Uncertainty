% LOCAL FIGURE FUNCTIONS
%
% These functions were previously separate files:
%   FigSpatialDistribution_Radius.m
%   Figure3.m
%
% They are embedded here so this manuscript figure/table script is
% self-contained for its spatial plotting and subplot layout.
% ========================================================================

function fig = FigSpatialDistribution_Radius( ...
    x, ...
    y, ...
    Data, ...
    ListOfModel, ...
    Model_Name, ...
    ListFunction, ...
    Function_Name, ...
    VNBoundaryLon, ...
    VNBoundaryLat, ...
    Fmt)
%% ========================================================================
% FIGSPATIALDISTRIBUTION_RADIUS_CURRENT
%
% Spatial distribution of effective neighbour radius.
%
% Expected input structure:
%
%   Data.(model_kernel).Radius_km
%
% Current arrangement:
%
%   Rows:
%       E08, GGP, EC4, GCO, SG2, X19
%
%   Columns:
%       G, M, T, C, L
%
% All manuscript-specific format settings are controlled outside this
% function through Fmt.
%
% The former Figure3 helper is embedded below as local function SubFig.
% The subplot-layout helper is embedded below as local function
% compact_subplot.
%
% Successful execution:
%   silent
%
% Errors/assertions remain active.
% ========================================================================


%% ========================================================================
% 1. BASIC CHECKS
% ========================================================================

nRow = ...
    numel(ListOfModel);


nCol = ...
    numel(ListFunction);


assert( ...
    numel(Model_Name) == nRow, ...
    'Model_Name and ListOfModel must have equal length.');


assert( ...
    numel(Function_Name) == nCol, ...
    'Function_Name and ListFunction must have equal length.');


assert( ...
    numel(Fmt.Panel.RowLabel) == nRow, ...
    'Incorrect number of row labels.');


assert( ...
    numel(Fmt.Panel.ColLabel) == nCol, ...
    'Incorrect number of column labels.');


x = ...
    x(:);


y = ...
    y(:);


assert( ...
    numel(x) == numel(y), ...
    'x and y must have equal length.');


%% ========================================================================
% 2. FIGURE
%
% Keep the same creation style used by the current manuscript figures.
% ========================================================================

fig = ...
    figure( ...
        'OuterPosition', ...
        Fmt.Figure.OuterPosition, ...
        'Color', ...
        Fmt.Figure.BackgroundColor);


%% ========================================================================
% 3. SUBPLOT LAYOUT
% ========================================================================

ha = ...
    compact_subplot( ...
        nRow, ...
        nCol, ...
        Fmt.Layout.Gap, ...
        Fmt.Layout.MarginHeight, ...
        Fmt.Layout.MarginWidth);


%% ========================================================================
% 4. PANELS
% ========================================================================

for i = 1:nRow

    for j = 1:nCol

        k = ...
            (i-1)*nCol + j;


        ax = ...
            ha(k);


        axes(ax);


        %% ----------------------------------------------------------------
        % DATA
        % -----------------------------------------------------------------

        runName = ...
            [ListOfModel{i} '_' ListFunction{j}];


        assert( ...
            isfield(Data,runName), ...
            'Missing radius data: %s', ...
            runName);


        assert( ...
            isfield(Data.(runName),'Radius_km'), ...
            'Missing Radius_km field: %s', ...
            runName);


        Radius = ...
            Data.(runName).Radius_km(:);


        assert( ...
            numel(Radius) == numel(x), ...
            'Radius/coordinate length mismatch: %s', ...
            runName);


        assert( ...
            all(isfinite(Radius)), ...
            'Nonfinite radius values: %s', ...
            runName);


        assert( ...
            all(Radius > 0), ...
            'Nonpositive radius values: %s', ...
            runName);


        %% ----------------------------------------------------------------
        % DRAW MAP
        % -----------------------------------------------------------------

        Legend = ...
            (i == 1 && j == 1);


        evalc( ...
            ['SubFig(' ...
             'x,y,Radius,' ...
             'VNBoundaryLon,VNBoundaryLat,' ...
             'Legend,Fmt.Marker.Size);']);


        %% ----------------------------------------------------------------
        % OPTIONAL COLOR LIMIT
        % -----------------------------------------------------------------

        if ~isempty(Fmt.ColorBar.CLim)

            caxis( ...
                ax, ...
                Fmt.ColorBar.CLim);

        end


        %% ----------------------------------------------------------------
        % OPTIONAL MAP LIMITS
        % -----------------------------------------------------------------

        if ~isempty(Fmt.Axis.XLim)

            xlim( ...
                ax, ...
                Fmt.Axis.XLim);

        end


        if ~isempty(Fmt.Axis.YLim)

            ylim( ...
                ax, ...
                Fmt.Axis.YLim);

        end


        %% ----------------------------------------------------------------
        % AXIS FONT
        % -----------------------------------------------------------------

        set( ...
            ax, ...
            'FontName', ...
            Fmt.Font.Name, ...
            'FontSize', ...
            Fmt.Font.AxisSize);


        %% ----------------------------------------------------------------
        % PANEL TEXT
        % -----------------------------------------------------------------

        PanelID = ...
            [ ...
            Fmt.Panel.RowLabel{i}, ...
            Fmt.Panel.ColLabel{j} ...
            ];


        text( ...
            ax, ...
            Fmt.Panel.X, ...
            Fmt.Panel.Y_ID, ...
            PanelID, ...
            'Units', ...
            Fmt.Panel.Units, ...
            'FontName', ...
            Fmt.Font.Name, ...
            'FontSize', ...
            Fmt.Font.PanelSize, ...
            'FontWeight', ...
            Fmt.Panel.FontWeight, ...
            'HorizontalAlignment', ...
            Fmt.Panel.HorizontalAlignment, ...
            'VerticalAlignment', ...
            Fmt.Panel.VerticalAlignment, ...
            'Interpreter', ...
            'none');


        text( ...
            ax, ...
            Fmt.Panel.X, ...
            Fmt.Panel.Y_Model, ...
            Model_Name{i}, ...
            'Units', ...
            Fmt.Panel.Units, ...
            'FontName', ...
            Fmt.Font.Name, ...
            'FontSize', ...
            Fmt.Font.PanelSize, ...
            'FontWeight', ...
            Fmt.Panel.FontWeight, ...
            'HorizontalAlignment', ...
            Fmt.Panel.HorizontalAlignment, ...
            'VerticalAlignment', ...
            Fmt.Panel.VerticalAlignment, ...
            'Interpreter', ...
            'none');


        text( ...
            ax, ...
            Fmt.Panel.X, ...
            Fmt.Panel.Y_Method, ...
            Function_Name{j}, ...
            'Units', ...
            Fmt.Panel.Units, ...
            'FontName', ...
            Fmt.Font.Name, ...
            'FontSize', ...
            Fmt.Font.PanelSize, ...
            'FontWeight', ...
            Fmt.Panel.FontWeight, ...
            'HorizontalAlignment', ...
            Fmt.Panel.HorizontalAlignment, ...
            'VerticalAlignment', ...
            Fmt.Panel.VerticalAlignment, ...
            'Interpreter', ...
            'none');


        %% ----------------------------------------------------------------
        % COLORBAR
        %
        % Keep MATLAB/SubFig default position.
        % No manual shift is applied.
        % -----------------------------------------------------------------

        cb = ...
            colorbar(ax);


        cb.FontName = ...
            Fmt.Font.Name;


        cb.FontSize = ...
            Fmt.Font.ColorBarSize;


        if Fmt.ColorBar.NumberTicks > 1

            lim = ...
                cb.Limits;


            ticks = ...
                linspace( ...
                    lim(1), ...
                    lim(2), ...
                    Fmt.ColorBar.NumberTicks);


            cb.Ticks = ...
                ticks;


            tickFormat = ...
                [ ...
                '%.' ...
                num2str(Fmt.ColorBar.Decimals) ...
                'f' ...
                ];


            cb.TickLabels = ...
                arrayfun( ...
                    @(z) sprintf(tickFormat,z), ...
                    ticks, ...
                    'UniformOutput', ...
                    false);

        end


        %% ----------------------------------------------------------------
        % TICK VISIBILITY
        % -----------------------------------------------------------------

        if j > 1

            ax.YTick = ...
                [];

        end


        if i < nRow

            ax.XTick = ...
                [];

        end


        %% ----------------------------------------------------------------
        % AXIS LABELS
        % -----------------------------------------------------------------

        if j == 1

            ylabel( ...
                ax, ...
                Fmt.Axis.YLabel, ...
                'FontName', ...
                Fmt.Font.Name, ...
                'FontSize', ...
                Fmt.Font.LabelSize);

        end


        if i == nRow

            xlabel( ...
                ax, ...
                Fmt.Axis.XLabel, ...
                'FontName', ...
                Fmt.Font.Name, ...
                'FontSize', ...
                Fmt.Font.LabelSize);

        end

    end

end


