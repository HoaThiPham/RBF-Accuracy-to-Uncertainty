%% ========================================================================
% 10. CALCULATE TABLE 2 FROM TRAINING SELECTED RADII
%
% Table 2 is based on selected radii at training points.
% Testing radii are transferred values and are shown in Figures fg:7/fg:9.
% ========================================================================

Case1Maximum = ...
    nan(nModel,nKernel);


Case2Maximum = ...
    nan(nModel,nKernel);


for i = 1:nModel

    for j = 1:nKernel

        runName = ...
            [ListOfModel{i} '_' ListFunction{j}];


        %% ----------------------------------------------------------------
        % CASE 1 TRAIN
        % -----------------------------------------------------------------

        assert( ...
            isfield(SelectedRadius.Case1.Train,runName), ...
            'Missing Case 1 Train radius: %s', ...
            runName);


        assert( ...
            isfield( ...
                SelectedRadius.Case1.Train.(runName), ...
                'Radius_km'), ...
            'Missing Case 1 Train Radius_km: %s', ...
            runName);


        V = ...
            SelectedRadius.Case1.Train. ...
            (runName).Radius_km(:);


        assert( ...
            all(isfinite(V)) && ...
            all(V > 0), ...
            'Invalid Case 1 Train radius: %s', ...
            runName);


        Case1Maximum(i,j) = ...
            max(V);


        %% ----------------------------------------------------------------
        % CASE 2 TRAIN
        % -----------------------------------------------------------------

        assert( ...
            isfield(SelectedRadius.Case2.Train,runName), ...
            'Missing Case 2 Train radius: %s', ...
            runName);


        assert( ...
            isfield( ...
                SelectedRadius.Case2.Train.(runName), ...
                'Radius_km'), ...
            'Missing Case 2 Train Radius_km: %s', ...
            runName);


        V = ...
            SelectedRadius.Case2.Train. ...
            (runName).Radius_km(:);


        assert( ...
            all(isfinite(V)) && ...
            all(V > 0), ...
            'Invalid Case 2 Train radius: %s', ...
            runName);


        Case2Maximum(i,j) = ...
            max(V);

    end

end


