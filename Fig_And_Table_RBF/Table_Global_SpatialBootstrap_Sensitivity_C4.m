%% ========================================================================
% PERCENTILE - NO STATISTICS TOOLBOX REQUIRED
% ========================================================================

function q = percentileLinear(x,p)


x = ...
    sort( ...
        double( ...
            x(isfinite(x))));


n = ...
    numel(x);


assert( ...
    n >= 1, ...
    'percentileLinear received no finite values.');


if n == 1

    q = ...
        x;

    return

end


r = ...
    1 + ...
    (n-1) * ...
    (p/100);


lo = ...
    floor(r);

hi = ...
    ceil(r);


if lo == hi

    q = ...
        x(lo);

else

    q = ...
        x(lo) + ...
        (r-lo) * ...
        (x(hi)-x(lo));

end

end


