function Outputs = Table_Global_SpatialBootstrap_Sensitivity_C4
%
% Create the compact manuscript Table C.4 directly from the SAVED Global
% bootstrap and variance-calibration MAT files.
%
% NO bootstrap, calibration, RBF fitting, or prediction is rerun.
%
% INPUTS, read from:
%   OutPut_RBF_2026
%
%   Case1_NonSpatialBootstrap.mat
%   Case2_NonSpatialBootstrap.mat
%   Case1_SpatialBootstrap.mat
%   Case2_SpatialBootstrap.mat
%   Case1_NonSpatialVarianceCalibration.mat
%   Case2_NonSpatialVarianceCalibration.mat
%   Case1_SpatialVarianceCalibration.mat
%   Case2_SpatialVarianceCalibration.mat
%
% COMPARISON:
%   NS = non-spatial bootstrap
%   S  = spatially stratified bootstrap
%
% CONSISTENCY WITH THE ESTABLISHED EXPORTER:
%   median(v), prctile(v,95), corrcoef(vNS,vS),
%   and exact calibration fields ASE_RMSE / RMSSE.
%
% For every Case and every one of the 30 GGM-kernel combinations:
%
%   dMedianVarPct = 100*(MedianVar_S - MedianVar_NS)/MedianVar_NS
%   dP95VarPct    = 100*(P95Var_S    - P95Var_NS   )/P95Var_NS
%
%   Corr_NS_S     = Pearson correlation between corresponding pointwise
%                   bootstrap variance vectors.
%
%   dASE_RMSE     = (ASE/RMSE)_S - (ASE/RMSE)_NS
%   dRMSSE        = RMSSE_S - RMSSE_NS
%
% FINAL MANUSCRIPT RULE:
% Use exactly the current six GGMs: EGM2008, ggmplus, eigen6c4, geco,
% sgg2, and xgm19. The legacy sgg1 is excluded. With five kernels,
% each case therefore summarizes exactly 6 x 5 = 30 combinations.
%
% Table C.4 then reports:
%   median / maximum ABSOLUTE variance changes;
%   median / minimum correlation;
%   median / maximum absolute calibration-metric changes.
%
% OUTPUTS:
%   Table_C4_Global_Bootstrap_Sensitivity.xlsx
%   Table_C4_Global_Bootstrap_Sensitivity.tex
%   Table_C4_Global_Bootstrap_Sensitivity.mat
%
% Excel sheets:
%   Summary
%   Case1_Detail_30
%   Case2_Detail_30
%   Definitions
%
% ========================================================================

clc

%% ========================================================================
% 1. PATHS
% ========================================================================

RootDir = '.';

DataDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026');

OutputDir = ...
    DataDir;

OutputExcel = ...
    fullfile( ...
        OutputDir, ...
        'Table_C4_Global_Bootstrap_Sensitivity.xlsx');

OutputTex = ...
    fullfile( ...
        OutputDir, ...
        'Table_C4_Global_Bootstrap_Sensitivity.tex');

OutputMAT = ...
    fullfile( ...
        OutputDir, ...
        'Table_C4_Global_Bootstrap_Sensitivity.mat');


%% ========================================================================
% 2. INPUT FILES
% ========================================================================

Files.Case1.BootstrapNS = ...
    fullfile(DataDir,'Case1_NonSpatialBootstrap.mat');

Files.Case2.BootstrapNS = ...
    fullfile(DataDir,'Case2_NonSpatialBootstrap.mat');

Files.Case1.BootstrapS = ...
    fullfile(DataDir,'Case1_SpatialBootstrap.mat');

Files.Case2.BootstrapS = ...
    fullfile(DataDir,'Case2_SpatialBootstrap.mat');

Files.Case1.CalibrationNS = ...
    fullfile(DataDir,'Case1_NonSpatialVarianceCalibration.mat');

Files.Case2.CalibrationNS = ...
    fullfile(DataDir,'Case2_NonSpatialVarianceCalibration.mat');

Files.Case1.CalibrationS = ...
    fullfile(DataDir,'Case1_SpatialVarianceCalibration.mat');

Files.Case2.CalibrationS = ...
    fullfile(DataDir,'Case2_SpatialVarianceCalibration.mat');


allFiles = { ...
    Files.Case1.BootstrapNS, ...
    Files.Case2.BootstrapNS, ...
    Files.Case1.BootstrapS, ...
    Files.Case2.BootstrapS, ...
    Files.Case1.CalibrationNS, ...
    Files.Case2.CalibrationNS, ...
    Files.Case1.CalibrationS, ...
    Files.Case2.CalibrationS};


for k = 1:numel(allFiles)

    assert( ...
        isfile(allFiles{k}), ...
        'Missing required input file:\n%s', ...
        allFiles{k});

end


%% ========================================================================
% 3. PROCESS BOTH CASES
% ========================================================================

CaseNames = {'Case1','Case2'};

% Authoritative CURRENT manuscript set.
% Older saved bootstrap files may still contain an extra legacy GGM.
TargetModels = { ...
    'EGM2008', ...
    'ggmplus', ...
    'eigen6c4', ...
    'geco', ...
    'sgg2', ...
    'xgm19'};

TargetKernels = { ...
    'gaussian', ...
    'multiquadric', ...
    'thinplate', ...
    'cubic', ...
    'linear'};

Detail = ...
    struct();

Audit = ...
    struct();


for ic = 1:2

    C = ...
        CaseNames{ic};


    BootstrapNS = ...
        loadMainStruct(Files.(C).BootstrapNS);

    BootstrapS = ...
        loadMainStruct(Files.(C).BootstrapS);

    CalibrationNS = ...
        loadMainStruct(Files.(C).CalibrationNS);

    CalibrationS = ...
        loadMainStruct(Files.(C).CalibrationS);


    [Detail.(C),Audit.(C)] = ...
        buildCaseDetail( ...
            BootstrapNS, ...
            CalibrationNS, ...
            BootstrapS, ...
            CalibrationS, ...
            C, ...
            TargetModels, ...
            TargetKernels);

end


%% ========================================================================
% 4. VALIDATE 30 GGM-KERNEL COMBINATIONS PER CASE
% ========================================================================

assert( ...
    height(Detail.Case1) == 30, ...
    'Case 1 must contain exactly 30 GGM-kernel combinations; found %d.', ...
    height(Detail.Case1));

assert( ...
    height(Detail.Case2) == 30, ...
    'Case 2 must contain exactly 30 GGM-kernel combinations; found %d.', ...
    height(Detail.Case2));


%% ========================================================================
% 5. BUILD COMPACT TABLE C.4 SUMMARY
% ========================================================================

Summary = ...
    buildSummaryTable( ...
        Detail.Case1, ...
        Detail.Case2);


%% ========================================================================
% 6. WRITE EXCEL
% ========================================================================

if isfile(OutputExcel)

    delete(OutputExcel);

end


writetable( ...
    Summary, ...
    OutputExcel, ...
    'Sheet', ...
    'Summary');


writetable( ...
    Detail.Case1, ...
    OutputExcel, ...
    'Sheet', ...
    'Case1_Detail_30');


writetable( ...
    Detail.Case2, ...
    OutputExcel, ...
    'Sheet', ...
    'Case2_Detail_30');


AuditTable = ...
    buildAuditTable(Audit);

writetable( ...
    AuditTable, ...
    OutputExcel, ...
    'Sheet', ...
    'Input_Audit');


Definitions = { ...
    'Symbol / quantity', 'Definition'; ...
    'NS', 'Non-spatial bootstrap'; ...
    'S', 'Spatially stratified bootstrap'; ...
    'MedianVar_NS', 'Median pointwise bootstrap variance under NS'; ...
    'MedianVar_S', 'Median pointwise bootstrap variance under S'; ...
    'AbsChangeMedianVar_pct', ...
        'abs(100*(MedianVar_S-MedianVar_NS)/MedianVar_NS)'; ...
    'P95Var_NS', '95th percentile of pointwise bootstrap variance under NS'; ...
    'P95Var_S', '95th percentile of pointwise bootstrap variance under S'; ...
    'AbsChangeP95Var_pct', ...
        'abs(100*(P95Var_S-P95Var_NS)/P95Var_NS)'; ...
    'Corr_NS_S', ...
        'Pearson correlation of paired pointwise NS and S variance vectors'; ...
    'AbsDelta_ASE_RMSE', ...
        'abs((ASE/RMSE)_S-(ASE/RMSE)_NS)'; ...
    'AbsDelta_RMSSE', ...
        'abs(RMSSE_S-RMSSE_NS)'; ...
    'Summary population', ...
        'Exactly 30 combinations per case = 6 current GGMs x 5 kernels; legacy sgg1 is excluded'};


writecell( ...
    Definitions, ...
    OutputExcel, ...
    'Sheet', ...
    'Definitions');


%% ========================================================================
% 7. WRITE LATEX TABLE C.4
% ========================================================================

writeLatexTableC4( ...
    OutputTex, ...
    Summary);


%% ========================================================================
% 8. SAVE MAT
% ========================================================================

save( ...
    OutputMAT, ...
    'Summary', ...
    'Detail', ...
    'Audit', ...
    'Files', ...
    'TargetModels', ...
    'TargetKernels', ...
    '-v7.3');


%% ========================================================================
% 9. REPORT
% ========================================================================

fprintf('\n=============================================================\n');
fprintf(' TABLE C.4 GLOBAL BOOTSTRAP SENSITIVITY COMPLETED\n');
fprintf('=============================================================\n');
fprintf('Case 1 rows : %d (6 GGMs x 5 kernels)\n',height(Detail.Case1));
fprintf('Case 2 rows : %d (6 GGMs x 5 kernels)\n',height(Detail.Case2));
fprintf('Case 1 excluded legacy models: %s\n',strjoin(cellstr(Audit.Case1.ExcludedModels),', '));
fprintf('Case 2 excluded legacy models: %s\n',strjoin(cellstr(Audit.Case2.ExcludedModels),', '));
fprintf('Excel       : %s\n',OutputExcel);
fprintf('LaTeX       : %s\n',OutputTex);
fprintf('MAT         : %s\n',OutputMAT);
fprintf('=============================================================\n');


Outputs = ...
    struct();


Outputs.Summary = ...
    Summary;

Outputs.Detail = ...
    Detail;

Outputs.Audit = ...
    Audit;

Outputs.ExcelFile = ...
    OutputExcel;

Outputs.LatexFile = ...
    OutputTex;

Outputs.MATFile = ...
    OutputMAT;

Outputs.InputFiles = ...
    Files;

end


%% ========================================================================
% BUILD ONE CASE: 30 GGM-KERNEL ROWS
% ========================================================================

function [T,Audit] = buildCaseDetail( ...
    BootstrapNS, ...
    CalibrationNS, ...
    BootstrapS, ...
    CalibrationS, ...
    CaseName, ...
    TargetModels, ...
    TargetKernels)


BootstrapNS = ...
    unwrapResults(BootstrapNS);

BootstrapS = ...
    unwrapResults(BootstrapS);

CalibrationNS = ...
    unwrapResults(CalibrationNS);

CalibrationS = ...
    unwrapResults(CalibrationS);


SourceModelsNS = ...
    string(BootstrapNS.ListOfModel(:));

SourceModelsS = ...
    string(BootstrapS.ListOfModel(:));

SourceKernelsNS = ...
    string(BootstrapNS.NameFunction_RBF(:));

SourceKernelsS = ...
    string(BootstrapS.NameFunction_RBF(:));


assert( ...
    isequal(SourceModelsNS,SourceModelsS), ...
    '%s: NS/S model lists differ.', ...
    CaseName);

assert( ...
    isequal(SourceKernelsNS,SourceKernelsS), ...
    '%s: NS/S kernel lists differ.', ...
    CaseName);


ModelsNS = ...
    string(TargetModels(:));

KernelsNS = ...
    string(TargetKernels(:));


for ii = 1:numel(ModelsNS)

    assert( ...
        any(strcmpi(SourceModelsNS,ModelsNS(ii))), ...
        '%s: required current GGM is missing from saved data: %s', ...
        CaseName, ...
        ModelsNS(ii));

end


for jj = 1:numel(KernelsNS)

    assert( ...
        any(strcmpi(SourceKernelsNS,KernelsNS(jj))), ...
        '%s: required kernel is missing from saved data: %s', ...
        CaseName, ...
        KernelsNS(jj));

end


ExcludedModels = ...
    SourceModelsNS( ...
        ~ismember(lower(SourceModelsNS),lower(ModelsNS)));


ExcludedKernels = ...
    SourceKernelsNS( ...
        ~ismember(lower(SourceKernelsNS),lower(KernelsNS)));


Audit = ...
    struct();

Audit.SourceModels = ...
    SourceModelsNS;

Audit.SourceKernels = ...
    SourceKernelsNS;

Audit.TargetModels = ...
    ModelsNS;

Audit.TargetKernels = ...
    KernelsNS;

Audit.ExcludedModels = ...
    ExcludedModels;

Audit.ExcludedKernels = ...
    ExcludedKernels;


nRows = ...
    numel(ModelsNS) * numel(KernelsNS);


Case = ...
    repmat(string(CaseName),nRows,1);

Model = ...
    strings(nRows,1);

Kernel = ...
    strings(nRows,1);


MedianVar_NS = ...
    nan(nRows,1);

MedianVar_S = ...
    nan(nRows,1);

ChangeMedianVar_pct = ...
    nan(nRows,1);

AbsChangeMedianVar_pct = ...
    nan(nRows,1);


P95Var_NS = ...
    nan(nRows,1);

P95Var_S = ...
    nan(nRows,1);

ChangeP95Var_pct = ...
    nan(nRows,1);

AbsChangeP95Var_pct = ...
    nan(nRows,1);


Corr_NS_S = ...
    nan(nRows,1);


ASE_RMSE_NS = ...
    nan(nRows,1);

ASE_RMSE_S = ...
    nan(nRows,1);

Delta_ASE_RMSE = ...
    nan(nRows,1);

AbsDelta_ASE_RMSE = ...
    nan(nRows,1);


RMSSE_NS = ...
    nan(nRows,1);

RMSSE_S = ...
    nan(nRows,1);

Delta_RMSSE = ...
    nan(nRows,1);

AbsDelta_RMSSE = ...
    nan(nRows,1);


row = ...
    0;


for i = 1:numel(ModelsNS)

    for j = 1:numel(KernelsNS)

        row = ...
            row + 1;


        model = ...
            ModelsNS(i);

        kernel = ...
            KernelsNS(j);


        Model(row) = ...
            model;

        Kernel(row) = ...
            kernel;


        % Exact run naming used by the established sensitivity exporter.
        runName = ...
            char( ...
                model + ...
                "_" + ...
                kernel);


        assert( ...
            isfield(BootstrapNS.Run,runName), ...
            '%s: missing NS bootstrap run %s.', ...
            CaseName, ...
            runName);

        assert( ...
            isfield(BootstrapS.Run,runName), ...
            '%s: missing S bootstrap run %s.', ...
            CaseName, ...
            runName);

        assert( ...
            isfield(CalibrationNS.Run,runName), ...
            '%s: missing NS calibration run %s.', ...
            CaseName, ...
            runName);

        assert( ...
            isfield(CalibrationS.Run,runName), ...
            '%s: missing S calibration run %s.', ...
            CaseName, ...
            runName);


        BNS = ...
            BootstrapNS.Run.(runName).Test;

        BS = ...
            BootstrapS.Run.(runName).Test;


        vNS = ...
            getVarianceVector(BNS);

        vS = ...
            getVarianceVector(BS);


        assert( ...
            numel(vNS) == numel(vS), ...
            '%s | %s | %s: NS/S test variance lengths differ.', ...
            CaseName, ...
            model, ...
            kernel);


        validNS = ...
            isfinite(vNS) & ...
            vNS >= 0;

        validS = ...
            isfinite(vS) & ...
            vS >= 0;


        assert( ...
            any(validNS), ...
            '%s | %s | %s: no valid NS test variances.', ...
            CaseName, ...
            model, ...
            kernel);

        assert( ...
            any(validS), ...
            '%s | %s | %s: no valid S test variances.', ...
            CaseName, ...
            model, ...
            kernel);


        MedianVar_NS(row) = ...
            median(vNS(validNS));

        MedianVar_S(row) = ...
            median(vS(validS));


        P95Var_NS(row) = ...
            prctile(vNS(validNS),95);

        P95Var_S(row) = ...
            prctile(vS(validS),95);


        assert( ...
            MedianVar_NS(row) > 0, ...
            '%s | %s | %s: NS median variance must be positive.', ...
            CaseName, ...
            model, ...
            kernel);


        assert( ...
            P95Var_NS(row) > 0, ...
            '%s | %s | %s: NS P95 variance must be positive.', ...
            CaseName, ...
            model, ...
            kernel);


        ChangeMedianVar_pct(row) = ...
            100 * ...
            (MedianVar_S(row) - MedianVar_NS(row)) / ...
            MedianVar_NS(row);


        AbsChangeMedianVar_pct(row) = ...
            abs(ChangeMedianVar_pct(row));


        ChangeP95Var_pct(row) = ...
            100 * ...
            (P95Var_S(row) - P95Var_NS(row)) / ...
            P95Var_NS(row);


        AbsChangeP95Var_pct(row) = ...
            abs(ChangeP95Var_pct(row));


        validPair = ...
            isfinite(vNS) & ...
            isfinite(vS);


        assert( ...
            nnz(validPair) >= 2, ...
            '%s | %s | %s: fewer than two paired variance values.', ...
            CaseName, ...
            model, ...
            kernel);


        CC = ...
            corrcoef( ...
                vNS(validPair), ...
                vS(validPair));


        Corr_NS_S(row) = ...
            CC(1,2);


        CNS = ...
            CalibrationNS.Run.(runName).Test;

        CS = ...
            CalibrationS.Run.(runName).Test;


        ASE_RMSE_NS(row) = ...
            getExactScalar( ...
                CNS, ...
                'ASE_RMSE');

        ASE_RMSE_S(row) = ...
            getExactScalar( ...
                CS, ...
                'ASE_RMSE');


        RMSSE_NS(row) = ...
            getExactScalar( ...
                CNS, ...
                'RMSSE');

        RMSSE_S(row) = ...
            getExactScalar( ...
                CS, ...
                'RMSSE');


        Delta_ASE_RMSE(row) = ...
            ASE_RMSE_S(row) - ...
            ASE_RMSE_NS(row);

        AbsDelta_ASE_RMSE(row) = ...
            abs(Delta_ASE_RMSE(row));


        Delta_RMSSE(row) = ...
            RMSSE_S(row) - ...
            RMSSE_NS(row);

        AbsDelta_RMSSE(row) = ...
            abs(Delta_RMSSE(row));

    end

end


T = ...
    table( ...
        Case, ...
        Model, ...
        Kernel, ...
        MedianVar_NS, ...
        MedianVar_S, ...
        ChangeMedianVar_pct, ...
        AbsChangeMedianVar_pct, ...
        P95Var_NS, ...
        P95Var_S, ...
        ChangeP95Var_pct, ...
        AbsChangeP95Var_pct, ...
        Corr_NS_S, ...
        ASE_RMSE_NS, ...
        ASE_RMSE_S, ...
        Delta_ASE_RMSE, ...
        AbsDelta_ASE_RMSE, ...
        RMSSE_NS, ...
        RMSSE_S, ...
        Delta_RMSSE, ...
        AbsDelta_RMSSE);


assert( ...
    all(isfinite(T.AbsChangeMedianVar_pct)), ...
    '%s: nonfinite median-variance changes.', ...
    CaseName);

assert( ...
    all(isfinite(T.AbsChangeP95Var_pct)), ...
    '%s: nonfinite P95-variance changes.', ...
    CaseName);

assert( ...
    all(isfinite(T.Corr_NS_S)), ...
    '%s: nonfinite NS/S correlations.', ...
    CaseName);

assert( ...
    all(isfinite(T.AbsDelta_ASE_RMSE)), ...
    '%s: nonfinite ASE/RMSE changes.', ...
    CaseName);

assert( ...
    all(isfinite(T.AbsDelta_RMSSE)), ...
    '%s: nonfinite RMSSE changes.', ...
    CaseName);

end


%% ========================================================================
% BUILD SUMMARY TABLE C.4
% ========================================================================

function T = buildSummaryTable(C1,C2)


Quantity = [ ...
    "Median absolute change in median variance (%)"; ...
    "Maximum absolute change in median variance (%)"; ...
    "Median absolute change in P95 variance (%)"; ...
    "Maximum absolute change in P95 variance (%)"; ...
    "Median Corr. (NS,S)"; ...
    "Minimum Corr. (NS,S)"; ...
    "Median |Delta ASE/RMSE|"; ...
    "Maximum |Delta ASE/RMSE|"; ...
    "Median |Delta RMSSE|"; ...
    "Maximum |Delta RMSSE|" ...
    ];


Case1 = [ ...
    median(C1.AbsChangeMedianVar_pct); ...
    max(C1.AbsChangeMedianVar_pct); ...
    median(C1.AbsChangeP95Var_pct); ...
    max(C1.AbsChangeP95Var_pct); ...
    median(C1.Corr_NS_S); ...
    min(C1.Corr_NS_S); ...
    median(C1.AbsDelta_ASE_RMSE); ...
    max(C1.AbsDelta_ASE_RMSE); ...
    median(C1.AbsDelta_RMSSE); ...
    max(C1.AbsDelta_RMSSE) ...
    ];


Case2 = [ ...
    median(C2.AbsChangeMedianVar_pct); ...
    max(C2.AbsChangeMedianVar_pct); ...
    median(C2.AbsChangeP95Var_pct); ...
    max(C2.AbsChangeP95Var_pct); ...
    median(C2.Corr_NS_S); ...
    min(C2.Corr_NS_S); ...
    median(C2.AbsDelta_ASE_RMSE); ...
    max(C2.AbsDelta_ASE_RMSE); ...
    median(C2.AbsDelta_RMSSE); ...
    max(C2.AbsDelta_RMSSE) ...
    ];


T = ...
    table( ...
        Quantity, ...
        Case1, ...
        Case2);

end


%% ========================================================================
% BUILD INPUT AUDIT TABLE
% ========================================================================

function T = buildAuditTable(Audit)

Case = strings(0,1);
Item = strings(0,1);
Value = strings(0,1);

cases = {'Case1','Case2'};

for ic = 1:numel(cases)

    C = cases{ic};
    A = Audit.(C);

    rows = { ...
        'Source models', strjoin(cellstr(A.SourceModels),', '); ...
        'Target manuscript models', strjoin(cellstr(A.TargetModels),', '); ...
        'Excluded legacy models', strjoin(cellstr(A.ExcludedModels),', '); ...
        'Source kernels', strjoin(cellstr(A.SourceKernels),', '); ...
        'Target manuscript kernels', strjoin(cellstr(A.TargetKernels),', '); ...
        'Excluded kernels', strjoin(cellstr(A.ExcludedKernels),', ')};

    for r = 1:size(rows,1)
        Case(end+1,1) = string(C); %#ok<AGROW>
        Item(end+1,1) = string(rows{r,1}); %#ok<AGROW>
        Value(end+1,1) = string(rows{r,2}); %#ok<AGROW>
    end
end

T = table(Case,Item,Value);

end


%% ========================================================================
% WRITE LATEX TABLE C.4
% ========================================================================

function writeLatexTableC4(OutputTex,T)


fid = ...
    fopen( ...
        OutputTex, ...
        'w');


assert( ...
    fid > 0, ...
    'Cannot create LaTeX file:\n%s', ...
    OutputTex);


cleanupObj = ...
    onCleanup(@() fclose(fid));


fprintf(fid,'%% Auto-generated from saved NS/S bootstrap + calibration MAT files\n');
fprintf(fid,'\\begin{table}[htbp]\n');
fprintf(fid,'\\centering\n');

fprintf(fid,[ ...
    '\\caption{Sensitivity of Global RBF uncertainty estimates to spatially ' ...
    'stratified bootstrap resampling on the independent test set.}\n']);

fprintf(fid,'\\label{tab:global_bootstrap_sensitivity}\n');
fprintf(fid,'\\small\n');
fprintf(fid,'\\begin{tabular}{lcc}\n');
fprintf(fid,'\\hline\n');
fprintf(fid,'Quantity & Case 1 & Case 2 \\\\\n');
fprintf(fid,'\\hline\n');


for r = 1:height(T)

    q = ...
        latexQuantity(T.Quantity(r));


    if r <= 4

        f1 = ...
            sprintf('%.2f',T.Case1(r));

        f2 = ...
            sprintf('%.2f',T.Case2(r));

    elseif r <= 6

        f1 = ...
            sprintf('%.3f',T.Case1(r));

        f2 = ...
            sprintf('%.3f',T.Case2(r));

    else

        f1 = ...
            sprintf('%.4f',T.Case1(r));

        f2 = ...
            sprintf('%.4f',T.Case2(r));

    end


    fprintf( ...
        fid, ...
        '%s & %s & %s \\\\\n', ...
        q, ...
        f1, ...
        f2);

end


fprintf(fid,'\\hline\n');
fprintf(fid,'\\end{tabular}\n');

fprintf(fid,'\\begin{flushleft}\n');
fprintf(fid,'\\footnotesize\n');

fprintf(fid,[ ...
    'Statistics summarise exactly 30 model--kernel combinations in each case ' ...
    '(six current GGMs by five kernels; legacy SSG1 is excluded). ' ...
    'NS and S denote the non-spatial and spatially stratified bootstrap, respectively. ' ...
    'Absolute variance changes are expressed as percentages relative to NS. ' ...
    'Corr. (NS,S) is the Pearson correlation between the corresponding pointwise ' ...
    'bootstrap variance estimates.\n']);

fprintf(fid,'\\end{flushleft}\n');
fprintf(fid,'\\end{table}\n');


clear cleanupObj

end


%% ========================================================================
% RESOLVE RUN FIELD
% ========================================================================

function runField = resolveRunField(RunStruct,model,kernel)


assert( ...
    isstruct(RunStruct), ...
    'Run must be a structure.');


names = ...
    string(fieldnames(RunStruct));


target1 = ...
    string(model) + ...
    "_" + ...
    string(kernel);


idx = ...
    find( ...
        strcmpi(names,target1), ...
        1);


if ~isempty(idx)

    runField = ...
        char(names(idx));

    return

end


targetNorm = ...
    normalizeToken( ...
        string(model) + ...
        string(kernel));


nameNorm = ...
    strings(size(names));


for k = 1:numel(names)

    nameNorm(k) = ...
        normalizeToken(names(k));

end


idx = ...
    find( ...
        contains(nameNorm,targetNorm), ...
        1);


assert( ...
    ~isempty(idx), ...
    'Cannot find Run field for model=%s, kernel=%s.', ...
    model, ...
    kernel);


if nnz(contains(nameNorm,targetNorm)) > 1

    exactTail = ...
        endsWith( ...
            nameNorm, ...
            targetNorm);


    if nnz(exactTail) == 1

        idx = ...
            find(exactTail,1);

    else

        error( ...
            'Ambiguous Run field for model=%s, kernel=%s.', ...
            model, ...
            kernel);

    end

end


runField = ...
    char(names(idx));

end


