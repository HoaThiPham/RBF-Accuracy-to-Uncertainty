%% ========================================================================
% LOAD MAIN STRUCT
% ========================================================================

function R = loadMainStruct(fileName)


S = ...
    load(fileName);


if isfield(S,'Results') && ...
   isstruct(S.Results)

    R = ...
        S.Results;

    return

end


names = ...
    fieldnames(S);


for k = 1:numel(names)

    x = ...
        S.(names{k});


    if isstruct(x) && ...
       isscalar(x) && ...
       isfield(x,'Results') && ...
       isstruct(x.Results)

        R = ...
            x.Results;

        return

    end

end


structNames = ...
    {};


for k = 1:numel(names)

    if isstruct(S.(names{k}))

        structNames{end+1} = ...
            names{k}; %#ok<AGROW>

    end

end


if numel(structNames) == 1

    R = ...
        S.(structNames{1});

    return

end


runCandidates = ...
    {};


for k = 1:numel(structNames)

    x = ...
        S.(structNames{k});


    if isfield(x,'Run')

        runCandidates{end+1} = ...
            structNames{k}; %#ok<AGROW>

    end

end


if numel(runCandidates) == 1

    R = ...
        S.(runCandidates{1});

    return

end


error( ...
    'Could not uniquely identify the main Results structure in:\n%s', ...
    fileName);

end


