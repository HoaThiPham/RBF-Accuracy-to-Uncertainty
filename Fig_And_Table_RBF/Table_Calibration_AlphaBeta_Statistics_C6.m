function Table_Calibration_AlphaBeta_Statistics_C6()
%% ========================================================================
% TABLE ALPHA AND BETA + CALIBRATION STATISTICS
%
% SINGLE-FUNCTION VERSION
%
% Current Global + Local variance calibration results
%
% Output:
%   1) LaTeX Table C6
%   2) Excel sheet: AlphaBeta
%   3) Excel sheet: Statistics
%   4) Command-window manuscript statistics
%
% Models:
%   E08, GGP, EC4, GCO, SG2, X19
%
% SGG1 excluded
%
% NO EXTERNAL HELPER FUNCTIONS REQUIRED
% ========================================================================

clc


%% ========================================================================
% USER INPUTS
% ========================================================================

RootDir = '.';


%% ------------------------------------------------------------------------
% GLOBAL CALIBRATION
% -------------------------------------------------------------------------

GlobalDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026');


GlobalFileCase1 = ...
    fullfile( ...
        GlobalDir, ...
        'Case1_NonSpatialVarianceCalibration.mat');


GlobalFileCase2 = ...
    fullfile( ...
        GlobalDir, ...
        'Case2_NonSpatialVarianceCalibration.mat');


%% ------------------------------------------------------------------------
% LOCAL CALIBRATION
% -------------------------------------------------------------------------

LocalDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'LocalVarianceCalibration_pseudo_unseen_B200_S0');


LocalFileCase1 = ...
    fullfile( ...
        LocalDir, ...
        'Case1_Local_VarianceCalibration.mat');


LocalFileCase2 = ...
    fullfile( ...
        LocalDir, ...
        'Case2_Local_VarianceCalibration.mat');


%% ------------------------------------------------------------------------
% OUTPUT
% -------------------------------------------------------------------------

OutputDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'CalibrationTables');


OutputBaseName = ...
    'Table_Calibration_AlphaBeta';


%% ------------------------------------------------------------------------
% MODELS
%
% SGG1 EXCLUDED
% -------------------------------------------------------------------------

Models = { ...
    'EGM2008', ...
    'ggmplus', ...
    'eigen6c4', ...
    'geco', ...
    'sgg2', ...
    'xgm19'};


ModelShort = { ...
    'E08', ...
    'GGP', ...
    'EC4', ...
    'GCO', ...
    'SG2', ...
    'X19'};


%% ------------------------------------------------------------------------
% KERNELS
% -------------------------------------------------------------------------

Kernels = { ...
    'gaussian', ...
    'multiquadric', ...
    'thinplate', ...
    'cubic', ...
    'linear'};


KernelShort = { ...
    'G', ...
    'M', ...
    'T', ...
    'C', ...
    'L'};


%% ------------------------------------------------------------------------
% TABLE ORDER
% -------------------------------------------------------------------------

CaseLabels = { ...
    'Case 1; Global', ...
    'Case 1; Local', ...
    'Case 2; Global', ...
    'Case 2; Local'};


InputFiles = { ...
    GlobalFileCase1, ...
    LocalFileCase1, ...
    GlobalFileCase2, ...
    LocalFileCase2};


%% ------------------------------------------------------------------------
% FORMAT
% -------------------------------------------------------------------------

NumDecimals = ...
    4;


TabColSep = ...
    4.5;


ArrayStretch = ...
    0.90;


TableCaption = ...
    'Calibration parameters \(\beta\) and \(\alpha\) by case/regime, EGM, and kernel.';


TableLabel = ...
    'tab3';


ExportLatex = ...
    true;


ExportExcel = ...
    true;


Tol = ...
    1e-10;


%% ========================================================================
% DIMENSIONS
% ========================================================================

nCase = ...
    numel(InputFiles);


nModel = ...
    numel(Models);


nKernel = ...
    numel(Kernels);


assert( ...
    nCase == numel(CaseLabels), ...
    'InputFiles and CaseLabels must have the same length.');


assert( ...
    nModel == numel(ModelShort), ...
    'Models and ModelShort must have the same length.');


assert( ...
    nKernel == numel(KernelShort), ...
    'Kernels and KernelShort must have the same length.');


assert( ...
    nKernel == 5, ...
    'Current table layout requires exactly five kernels.');


%% ========================================================================
% CHECK FILES
% ========================================================================

for q = 1:nCase

    assert( ...
        isfile(InputFiles{q}), ...
        'Calibration file not found: %s', ...
        InputFiles{q});

end


if ~isfolder(OutputDir)

    mkdir(OutputDir);

end


LatexFile = ...
    fullfile( ...
        OutputDir, ...
        [OutputBaseName '.tex']);


ExcelFile = ...
    fullfile( ...
        OutputDir, ...
        [OutputBaseName '.xlsx']);


%% ========================================================================
% SHOW INPUT FILES
% ========================================================================

fprintf('\n');
fprintf('=============================================================\n');
fprintf(' CALIBRATION TABLE INPUTS\n');
fprintf('=============================================================\n');


fprintf( ...
    'Case 1 Global : %s\n', ...
    InputFiles{1});


fprintf( ...
    'Case 1 Local  : %s\n', ...
    InputFiles{2});


fprintf( ...
    'Case 2 Global : %s\n', ...
    InputFiles{3});


fprintf( ...
    'Case 2 Local  : %s\n', ...
    InputFiles{4});


fprintf('=============================================================\n');


%% ========================================================================
% LOAD ALL CALIBRATION STRUCTURES
%
% Everything is done inside this function.
% ========================================================================

Cases = ...
    cell(nCase,1);


PreferredVariableNames = { ...
    'CalibrationCase1', ...
    'CalibrationCase2', ...
    'Calibration', ...
    'Results'};


for q = 1:nCase

    FileName = ...
        InputFiles{q};


    Info = ...
        whos( ...
            '-file', ...
            FileName);


    assert( ...
        ~isempty(Info), ...
        'Calibration file is empty: %s', ...
        FileName);


    FileVariables = ...
        {Info.name};


    C = ...
        [];


    Found = ...
        false;


    %% --------------------------------------------------------------------
    % First: preferred variable names
    % ---------------------------------------------------------------------

    for k = 1:numel(PreferredVariableNames)

        VariableName = ...
            PreferredVariableNames{k};


        if any(strcmp(FileVariables,VariableName))

            S = ...
                load( ...
                    FileName, ...
                    VariableName);


            X = ...
                S.(VariableName);


            if isstruct(X) && ...
                    isfield(X,'Run')

                C = ...
                    X;


                Found = ...
                    true;


                break

            end

        end

    end


    %% --------------------------------------------------------------------
    % Second: generic struct fallback
    % ---------------------------------------------------------------------

    if ~Found

        for k = 1:numel(Info)

            if strcmp( ...
                    Info(k).class, ...
                    'struct')

                VariableName = ...
                    Info(k).name;


                S = ...
                    load( ...
                        FileName, ...
                        VariableName);


                X = ...
                    S.(VariableName);


                if isstruct(X) && ...
                        isfield(X,'Run')

                    C = ...
                        X;


                    Found = ...
                        true;


                    break

                end

            end

        end

    end


    assert( ...
        Found, ...
        ['No calibration structure containing field "Run" ' ...
         'was found in:\n%s'], ...
        FileName);


    Cases{q} = ...
        C;

end


%% ========================================================================
% COLLECT ALPHA AND BETA
% ========================================================================

AlphaAll = ...
    cell(nCase,1);


BetaAll = ...
    cell(nCase,1);


for q = 1:nCase

    C = ...
        Cases{q};


    Alpha = ...
        nan(nModel,nKernel);


    Beta = ...
        nan(nModel,nKernel);


    %% ====================================================================
    % GET MODEL / KERNEL LISTS FOR RUN MAPPING
    % ====================================================================

    modelListStored = ...
        [];


    kernelListStored = ...
        [];


    if isfield(C,'ListOfModel')

        modelListStored = ...
            C.ListOfModel;


    elseif isfield(C,'ModelNames')

        modelListStored = ...
            C.ModelNames;

    end


    if isfield(C,'NameFunction_RBF')

        kernelListStored = ...
            C.NameFunction_RBF;


    elseif isfield(C,'KernelNames')

        kernelListStored = ...
            C.KernelNames;

    end


    %% --------------------------------------------------------------------
    % Source fallback
    % ---------------------------------------------------------------------

    if isempty(modelListStored) && ...
            isfield(C,'Source') && ...
            isstruct(C.Source)

        if isfield(C.Source,'ListOfModel')

            modelListStored = ...
                C.Source.ListOfModel;

        end

    end


    if isempty(kernelListStored) && ...
            isfield(C,'Source') && ...
            isstruct(C.Source)

        if isfield(C.Source,'NameFunction_RBF')

            kernelListStored = ...
                C.Source.NameFunction_RBF;

        end

    end


    %% ====================================================================
    % LOOP MODELS / KERNELS
    % ====================================================================

    for i = 1:nModel

        modelName = ...
            Models{i};


        for j = 1:nKernel

            kernelName = ...
                Kernels{j};


            runName = ...
                '';


            FoundRun = ...
                false;


            %% ============================================================
            % OPTION 1: CANONICAL RUN NAME
            % ============================================================

            canonicalName = ...
                [modelName '_' kernelName];


            if isfield(C.Run,canonicalName)

                runName = ...
                    canonicalName;


                FoundRun = ...
                    true;

            end


            %% ============================================================
            % OPTION 2: STORED RUN FIELD MATRIX
            % ============================================================

            if ~FoundRun && ...
                    ~isempty(modelListStored) && ...
                    ~isempty(kernelListStored) && ...
                    isfield(C,'RunFieldMatrix')

                mList = ...
                    string(modelListStored(:));


                kList = ...
                    string(kernelListStored(:));


                iModelStored = ...
                    find( ...
                        strcmpi( ...
                            mList, ...
                            modelName), ...
                        1);


                iKernelStored = ...
                    find( ...
                        strcmpi( ...
                            kList, ...
                            kernelName), ...
                        1);


                if ~isempty(iModelStored) && ...
                        ~isempty(iKernelStored) && ...
                        size(C.RunFieldMatrix,1) >= iModelStored && ...
                        size(C.RunFieldMatrix,2) >= iKernelStored

                    candidate = ...
                        C.RunFieldMatrix{iModelStored,iKernelStored};


                    if ~isempty(candidate)

                        candidate = ...
                            char(candidate);


                        if isfield(C.Run,candidate)

                            runName = ...
                                candidate;


                            FoundRun = ...
                                true;

                        end

                    end

                end

            end


            %% ============================================================
            % OPTION 3: LEGACY LOCAL NAME
            % ============================================================

            if ~FoundRun

                runFields = ...
                    fieldnames(C.Run);


                token = ...
                    ['_' modelName '_' kernelName];


                idx = ...
                    contains( ...
                        runFields, ...
                        token, ...
                        'IgnoreCase', ...
                        true);


                if nnz(idx) == 1

                    runName = ...
                        runFields{idx};


                    FoundRun = ...
                        true;

                end

            end


            %% ============================================================
            % FINAL CHECK
            % ============================================================

            assert( ...
                FoundRun, ...
                ['Cannot uniquely resolve calibration run for ' ...
                 'Case="%s", Model="%s", Kernel="%s".'], ...
                CaseLabels{q}, ...
                modelName, ...
                kernelName);


            R = ...
                C.Run.(runName);


            assert( ...
                isfield(R,'alpha'), ...
                'alpha missing: %s / %s / %s.', ...
                CaseLabels{q}, ...
                modelName, ...
                kernelName);


            assert( ...
                isfield(R,'beta'), ...
                'beta missing: %s / %s / %s.', ...
                CaseLabels{q}, ...
                modelName, ...
                kernelName);


            Alpha(i,j) = ...
                double(R.alpha);


            Beta(i,j) = ...
                double(R.beta);

        end

    end


    AlphaAll{q} = ...
        Alpha;


    BetaAll{q} = ...
        Beta;

end


%% ========================================================================
% CHECK COLLECTED VALUES
% ========================================================================

for q = 1:nCase

    assert( ...
        all(isfinite(AlphaAll{q}(:))), ...
        'Non-finite alpha values found in %s.', ...
        CaseLabels{q});


    assert( ...
        all(isfinite(BetaAll{q}(:))), ...
        'Non-finite beta values found in %s.', ...
        CaseLabels{q});

end


%% ========================================================================
% POOLED ALPHA AND BETA
% ========================================================================

BetaPooled = ...
    vertcat( ...
        BetaAll{:});


BetaPooled = ...
    BetaPooled(:);


AlphaPooled = ...
    vertcat( ...
        AlphaAll{:});


AlphaPooled = ...
    AlphaPooled(:);


nPooled = ...
    numel(BetaPooled);


%% ========================================================================
% STATISTICS TABLE
% ========================================================================

SummaryNames = { ...
    'Case 1; Global', ...
    'Case 1; Local', ...
    'Case 2; Global', ...
    'Case 2; Local', ...
    'All'};


CalibrationStatistics = ...
    table( ...
    'Size',[5 16], ...
    'VariableTypes',{ ...
        'string', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double', ...
        'double'}, ...
    'VariableNames',{ ...
        'Group', ...
        'N', ...
        'BetaMean', ...
        'BetaMedian', ...
        'BetaMin', ...
        'BetaMax', ...
        'BetaGT1_N', ...
        'BetaGT1_Percent', ...
        'BetaEQ1_N', ...
        'BetaEQ1_Percent', ...
        'AlphaMean', ...
        'AlphaMedian', ...
        'AlphaMin', ...
        'AlphaMax', ...
        'AlphaGT0_N', ...
        'AlphaGT0_Percent'});


%% ========================================================================
% CASE / REGIME STATISTICS
% ========================================================================

for q = 1:nCase

    B = ...
        BetaAll{q}(:);


    A = ...
        AlphaAll{q}(:);


    n = ...
        numel(B);


    nBetaGT1 = ...
        nnz(B > 1 + Tol);


    nBetaEQ1 = ...
        nnz(abs(B - 1) <= Tol);


    nAlphaGT0 = ...
        nnz(A > Tol);


    CalibrationStatistics(q,:) = { ...
        string(SummaryNames{q}), ...
        n, ...
        mean(B), ...
        median(B), ...
        min(B), ...
        max(B), ...
        nBetaGT1, ...
        100*nBetaGT1/n, ...
        nBetaEQ1, ...
        100*nBetaEQ1/n, ...
        mean(A), ...
        median(A), ...
        min(A), ...
        max(A), ...
        nAlphaGT0, ...
        100*nAlphaGT0/n};

end


%% ========================================================================
% POOLED STATISTICS
% ========================================================================

nBetaGT1Pooled = ...
    nnz(BetaPooled > 1 + Tol);


nBetaEQ1Pooled = ...
    nnz(abs(BetaPooled - 1) <= Tol);


nAlphaGT0Pooled = ...
    nnz(AlphaPooled > Tol);


CalibrationStatistics(5,:) = { ...
    "All", ...
    nPooled, ...
    mean(BetaPooled), ...
    median(BetaPooled), ...
    min(BetaPooled), ...
    max(BetaPooled), ...
    nBetaGT1Pooled, ...
    100*nBetaGT1Pooled/nPooled, ...
    nBetaEQ1Pooled, ...
    100*nBetaEQ1Pooled/nPooled, ...
    mean(AlphaPooled), ...
    median(AlphaPooled), ...
    min(AlphaPooled), ...
    max(AlphaPooled), ...
    nAlphaGT0Pooled, ...
    100*nAlphaGT0Pooled/nPooled};


%% ========================================================================
% DISPLAY CALIBRATION STATISTICS
% ========================================================================

fprintf('\n');
fprintf('=============================================================\n');
fprintf(' CALIBRATION PARAMETER STATISTICS\n');
fprintf('=============================================================\n');


for q = 1:height(CalibrationStatistics)

    fprintf( ...
        '\n%s\n', ...
        CalibrationStatistics.Group(q));


    fprintf( ...
        'N                 = %d\n', ...
        CalibrationStatistics.N(q));


    fprintf( ...
        'Beta mean         = %.6f\n', ...
        CalibrationStatistics.BetaMean(q));


    fprintf( ...
        'Beta median       = %.6f\n', ...
        CalibrationStatistics.BetaMedian(q));


    fprintf( ...
        'Beta range        = %.6f - %.6f\n', ...
        CalibrationStatistics.BetaMin(q), ...
        CalibrationStatistics.BetaMax(q));


    fprintf( ...
        'Beta > 1          = %d / %d (%.1f%%)\n', ...
        CalibrationStatistics.BetaGT1_N(q), ...
        CalibrationStatistics.N(q), ...
        CalibrationStatistics.BetaGT1_Percent(q));


    fprintf( ...
        'Beta = 1          = %d / %d (%.1f%%)\n', ...
        CalibrationStatistics.BetaEQ1_N(q), ...
        CalibrationStatistics.N(q), ...
        CalibrationStatistics.BetaEQ1_Percent(q));


    fprintf( ...
        'Alpha mean        = %.6f\n', ...
        CalibrationStatistics.AlphaMean(q));


    fprintf( ...
        'Alpha median      = %.6f\n', ...
        CalibrationStatistics.AlphaMedian(q));


    fprintf( ...
        'Alpha range       = %.6f - %.6f\n', ...
        CalibrationStatistics.AlphaMin(q), ...
        CalibrationStatistics.AlphaMax(q));


    fprintf( ...
        'Alpha > 0         = %d / %d (%.1f%%)\n', ...
        CalibrationStatistics.AlphaGT0_N(q), ...
        CalibrationStatistics.N(q), ...
        CalibrationStatistics.AlphaGT0_Percent(q));

end


%% ========================================================================
% MANUSCRIPT VALUES
% ========================================================================

fprintf('\n');
fprintf('-------------------------------------------------------------\n');
fprintf(' MANUSCRIPT VALUES\n');
fprintf('-------------------------------------------------------------\n');


fprintf( ...
    'Mean beta       = %.4f\n', ...
    mean(BetaPooled));


fprintf( ...
    'Median beta     = %.4f\n', ...
    median(BetaPooled));


fprintf( ...
    'Beta range      = %.4f - %.4f\n', ...
    min(BetaPooled), ...
    max(BetaPooled));


fprintf( ...
    'Beta > 1        = %d / %d (%.1f%%)\n', ...
    nBetaGT1Pooled, ...
    nPooled, ...
    100*nBetaGT1Pooled/nPooled);


fprintf( ...
    'Beta = 1        = %d / %d (%.1f%%)\n', ...
    nBetaEQ1Pooled, ...
    nPooled, ...
    100*nBetaEQ1Pooled/nPooled);


fprintf('\n');


fprintf( ...
    'Mean alpha      = %.4f\n', ...
    mean(AlphaPooled));


fprintf( ...
    'Median alpha    = %.4f\n', ...
    median(AlphaPooled));


fprintf( ...
    'Alpha range     = %.4f - %.4f\n', ...
    min(AlphaPooled), ...
    max(AlphaPooled));


fprintf( ...
    'Alpha > 0       = %d / %d (%.1f%%)\n', ...
    nAlphaGT0Pooled, ...
    nPooled, ...
    100*nAlphaGT0Pooled/nPooled);


fprintf('=============================================================\n');


%% ========================================================================
% CREATE LATEX TABLE
%
% EXACT FORMAT OF OLD MANUSCRIPT TABLE
%
% ONLY CHANGES:
%   1. SG1 / SGG1 removed
%   2. multirow automatically becomes 6
%   3. current beta and alpha values inserted
% ========================================================================

Lines = ...
    {};


%% ------------------------------------------------------------------------
% TABLE START
% -------------------------------------------------------------------------

Lines{end+1} = ...
    '\begin{table}[H]';

Lines{end+1} = ...
    '\centering';

Lines{end+1} = ...
    ['\caption{' TableCaption '}'];

Lines{end+1} = ...
    ['\label{' TableLabel '}'];

Lines{end+1} = ...
    sprintf( ...
        '\\setlength{\\tabcolsep}{%.1f pt}', ...
        TabColSep);

Lines{end+1} = ...
    sprintf( ...
        '\\renewcommand{\\arraystretch}{%.2f}', ...
        ArrayStretch);

Lines{end+1} = ...
    '% columns: 1 (Case/Regime) + 1 (EGM) + 5 beta + 5 alpha = 12';


%% ------------------------------------------------------------------------
% EXACT OLD COLUMN FORMAT
% -------------------------------------------------------------------------

Lines{end+1} = ...
    '\begin{tabular}{@{} ll *{5}{r} *{5}{r} @{}}';


%% ------------------------------------------------------------------------
% EXACT OLD HEADER
% -------------------------------------------------------------------------

Lines{end+1} = ...
    '\toprule';

Lines{end+1} = ...
    '\multicolumn{2}{c}{} &';

Lines{end+1} = ...
    '\multicolumn{5}{c}{\(\beta\)} &';

Lines{end+1} = ...
    '\multicolumn{5}{c}{\(\alpha\)} \\';

Lines{end+1} = ...
    '\cmidrule(lr){3-7}\cmidrule(lr){8-12}';

Lines{end+1} = ...
    '\shortstack[l]{\textbf{Case;}\\ \textbf{Regime}} & \textbf{EGM} &';

Lines{end+1} = ...
    '\textbf{G} & \textbf{M} & \textbf{T} & \textbf{C} & \textbf{L} &';

Lines{end+1} = ...
    '\textbf{G} & \textbf{M} & \textbf{T} & \textbf{C} & \textbf{L} \\';

Lines{end+1} = ...
    '\midrule';

Lines{end+1} = ...
    '';


%% ========================================================================
% TABLE BODY
% ========================================================================

for q = 1:nCase

    Beta = ...
        BetaAll{q};

    Alpha = ...
        AlphaAll{q};


    %% --------------------------------------------------------------------
    % SPLIT CASE LABEL
    % ---------------------------------------------------------------------

    Parts = ...
        strsplit( ...
            CaseLabels{q}, ...
            ';');


    assert( ...
        numel(Parts) == 2, ...
        'CaseLabels must have format "Case N; Regime".');


    CaseText = ...
        strtrim(Parts{1});

    RegimeText = ...
        strtrim(Parts{2});


    % Exact appearance:
    %
    % Case 1;
    % Global
    %
    LatexCaseLabel = ...
        sprintf( ...
            '%s;\\\\ %s', ...
            CaseText, ...
            RegimeText);


    %% --------------------------------------------------------------------
    % CURRENT SIX MODELS:
    %
    % E08
    % GGP
    % EC4
    % GCO
    % SG2
    % X19
    %
    % SG1 REMOVED
    % ---------------------------------------------------------------------

    for i = 1:nModel

        ValueCells = ...
            cell(1,2*nKernel);


        %% Beta
        for j = 1:nKernel

            ValueCells{j} = ...
                sprintf( ...
                    ['%.' num2str(NumDecimals) 'f'], ...
                    Beta(i,j));

        end


        %% Alpha
        for j = 1:nKernel

            ValueCells{nKernel+j} = ...
                sprintf( ...
                    ['%.' num2str(NumDecimals) 'f'], ...
                    Alpha(i,j));

        end


        ValueText = ...
            strjoin( ...
                ValueCells, ...
                ' & ');


        %% ---------------------------------------------------------------
        % FIRST EGM ROW
        %
        % Old:
        % \multirow{7}{*}{...}
        %
        % Current:
        % \multirow{6}{*}{...}
        % ---------------------------------------------------------------

        if i == 1

            Row = ...
                sprintf( ...
                    ['\\multirow{%d}{*}{\\shortstack[l]{%s}} ' ...
                     '& %s & %s \\\\'], ...
                    nModel, ...
                    LatexCaseLabel, ...
                    ModelShort{i}, ...
                    ValueText);


        %% ---------------------------------------------------------------
        % REMAINING EGM ROWS
        % ---------------------------------------------------------------

        else

            Row = ...
                sprintf( ...
                    ' & %s & %s \\\\', ...
                    ModelShort{i}, ...
                    ValueText);

        end


        Lines{end+1} = ...
            Row;

    end


    %% --------------------------------------------------------------------
    % SAME MIDRULE BETWEEN BLOCKS
    % ---------------------------------------------------------------------

    if q < nCase

        Lines{end+1} = ...
            '\midrule';

        Lines{end+1} = ...
            '';

    end

end


%% ------------------------------------------------------------------------
% EXACT OLD TABLE END
% -------------------------------------------------------------------------

Lines{end+1} = ...
    '\bottomrule';

Lines{end+1} = ...
    '\end{tabular}';

Lines{end+1} = ...
    '\end{table}';


%% ========================================================================
% BUILD LATEX STRING
% ========================================================================

LatexText = ...
    strjoin( ...
        Lines, ...
        newline);



%% ========================================================================
% SAVE LATEX
% ========================================================================

if ExportLatex

    fid = ...
        fopen( ...
            LatexFile, ...
            'w');


    assert( ...
        fid >= 0, ...
        'Cannot create LaTeX file: %s', ...
        LatexFile);


    fprintf( ...
        fid, ...
        '%s\n', ...
        LatexText);


    fclose(fid);

end


%% ========================================================================
% CREATE EXCEL
% ========================================================================

if ExportExcel

    if isfile(ExcelFile)

        delete(ExcelFile);

    end


    ExcelData = ...
        cell( ...
            2 + nCase*nModel, ...
            2 + 2*nKernel);


    %% --------------------------------------------------------------------
    % HEADER ROW 1
    % ---------------------------------------------------------------------

    ExcelData(1,:) = { ...
        '', ...
        '', ...
        'Beta', ...
        'Beta', ...
        'Beta', ...
        'Beta', ...
        'Beta', ...
        'Alpha', ...
        'Alpha', ...
