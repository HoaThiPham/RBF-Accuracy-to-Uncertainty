function Outputs =Table_RunTime_C13()
%CREATE_TABLE_C13_RUNTIME 
%
% ONE-FILE FAST WORKFLOW FOR MANUSCRIPT TABLE C.13
%
% This function:
%   1) reuses Current_Runtime_Manuscript.mat immediately when valid;
%   2) otherwise reads only the saved runtime quantities needed for Table C.13;
%   3) never reruns RBF fitting, optimization, testing, or bootstrap;
%   4) creates the compact Excel and LaTeX Table C.13.
%
% FAST COLLECTION STRATEGY
% ------------------------
% Global fitting:
%   Read saved Results.trainWallTime / testWallTime.
%
% Local fitting:
%   Stage 2: selective HDF5 reads of trainWallTime / testWallTime only.
%   Stage 1: read only Stage1Diag.stage1WallTime from the 30 DIAG files
%            for each case. Stage-1 CORE/TRACE payloads are never loaded.
%
% Local complete training:
%   Stage1 wall time + Stage2 trainWallTime.
%
% Bootstrap:
%   Try selective HDF5 runtime reads first.
%   If the saved matrix contains a legacy extra GGM and therefore requires
%   source-label metadata for filtering, safely fall back to loading Results
%   for that bootstrap file only.
%
% TABLE CELL
% ----------
%   Training / Testing / Bootstrap
%
% UNIT
% ----
%   minutes
%
% DISPLAY RULE
% ------------
%   < 1 min -> <1
%   >=1 min -> nearest integer
%
% Textual ranges in Excel use the underlying UNROUNDED minute records.
%
% OUTPUT FOLDER
% -------------
%   OutPut_RBF_2026_2\Manuscript\tables\
%
% OUTPUT FILES
% ------------
% Current_Runtime_Manuscript.mat
% Table_C13_Runtime.xlsx
% Table_C13_Runtime.tex
%
% ========================================================================

clc
tAll = tic;

%% ========================================================================
% 1. USER CONTROL
% ========================================================================

% Recommended:
%   false = reuse an already valid Current_Runtime_Manuscript.mat.
%   true  = force runtime recollection from the saved source files.
FORCE_RECOLLECT = false;

%% ========================================================================
% 2. ROOTS / CURRENT MANUSCRIPT ORDER
% ========================================================================

RootDir = '.';
GlobalRoot = ...
    fullfile(RootDir,'OutPut_RBF_2026');

