    'E08', ...
    'GGP', ...
    'EC4', ...
    'GCO', ...
    'SG2', ...
    'X19'};

Kernels = { ...
    'gaussian', ...
    'multiquadric', ...
    'thinplate', ...
    'cubic', ...
    'linear'};

