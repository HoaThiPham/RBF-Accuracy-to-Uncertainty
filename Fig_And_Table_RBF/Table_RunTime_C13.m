% LOCAL FUNCTION: TEXTUAL RANGES FROM UNROUNDED RECORDS
% ========================================================================

function T = buildRangeTable(Runtime)

Cases = ...
    {'Case1','Case2'};

Regimes = ...
    {'Global','Local'};

Case = strings(0,1);
Regime = strings(0,1);
Metric = strings(0,1);

Minimum_min = zeros(0,1);
Maximum_min = zeros(0,1);
Range_text = strings(0,1);

for ic = 1:2

    for ir = 1:2

        C = ...
            Cases{ic};

        Rg = ...
            Regimes{ir};

        D = ...
            Runtime.(C).(Rg);

        Train = ...
            getRuntimeField( ...
                D, ...
                {'Training_s','TrainingWall_s'}) / 60;

        Test = ...
            getRuntimeField( ...
                D, ...
                {'Testing_s','TestingWall_s'}) / 60;

        Boot = ...
            getRuntimeField( ...
                D, ...
                {'Bootstrap_s','BootstrapWall_s'}) / 60;

        Names = ...
            {'Training','Testing','Bootstrap'};

        Values = ...
            {Train,Test,Boot};

        for q = 1:3

            x = ...
                Values{q};

            x = ...
                x(isfinite(x));

            assert( ...
                ~isempty(x), ...
                'No finite values for %s / %s / %s.', ...
                C, ...
                Rg, ...
                Names{q});

            mn = ...
                min(x);

            mx = ...
                max(x);

            Case(end+1,1) = ...
                string(C); %#ok<AGROW>

            Regime(end+1,1) = ...
                string(Rg); %#ok<AGROW>

