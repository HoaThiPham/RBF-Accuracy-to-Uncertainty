%% ========================================================================
% LOCAL FUNCTION: NORMALIZE OLD/NEW RUNTIME FIELD NAMES
% ========================================================================

function Runtime = normalizeRuntimeNames(Runtime)

Cases = ...
    {'Case1','Case2'};

Regimes = ...
    {'Global','Local'};

for ic = 1:2

    for ir = 1:2

        C = ...
            Cases{ic};

        Rg = ...
            Regimes{ir};

        X = ...
            Runtime.(C).(Rg);

        if ~isfield(X,'Training_s')

            if isfield(X,'TrainingWall_s')

                X.Training_s = ...
                    X.TrainingWall_s;

            else

                error( ...
                    'Missing %s.%s training runtime.', ...
                    C, ...
                    Rg);

            end

        end

        if ~isfield(X,'Testing_s')

            if isfield(X,'TestingWall_s')

                X.Testing_s = ...
                    X.TestingWall_s;

            else

                error( ...
                    'Missing %s.%s testing runtime.', ...
                    C, ...
                    Rg);

            end

        end

        if ~isfield(X,'Bootstrap_s')

            if isfield(X,'BootstrapWall_s')

                X.Bootstrap_s = ...
                    X.BootstrapWall_s;

            else

                error( ...
                    'Missing %s.%s bootstrap runtime.', ...
                    C, ...
                    Rg);

            end

        end

        Runtime.(C).(Rg) = ...
            X;

    end

end

end


