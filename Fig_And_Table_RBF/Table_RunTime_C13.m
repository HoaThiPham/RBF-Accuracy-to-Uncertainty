    fullfile(LocalBootstrapRoot,'Case1_Local_Bootstrap.mat');

LocalBootstrapCase2File = ...
    fullfile(LocalBootstrapRoot,'Case2_Local_Bootstrap.mat');

%% ========================================================================
% 4. OUTPUTS
% ========================================================================

OutputDir = ...
    fullfile( ...
        LocalRoot, ...
        'Manuscript', ...
        'tables');

if ~isfolder(OutputDir)
    mkdir(OutputDir);
end

RuntimeMAT = ...
    fullfile( ...
        OutputDir, ...
        'Current_Runtime_Manuscript.mat');

ExcelFile = ...
    fullfile( ...
        OutputDir, ...
        'Table_C13_Runtime.xlsx');

LatexFile = ...
    fullfile( ...
        OutputDir, ...
        'Table_C13_Runtime.tex');

%% ========================================================================
% 5. FAST CACHE REUSE
% ========================================================================

usedExistingRuntime = false;

if ~FORCE_RECOLLECT && isfile(RuntimeMAT)

    try

        C = ...
            load( ...
                RuntimeMAT, ...
                'Runtime', ...
                'ModelShort', ...
                'KernelShort');

        assert(isfield(C,'Runtime'), ...
            'Cached MAT does not contain Runtime.');

        validateRuntimeContainer( ...
            C.Runtime, ...
            nModel, ...
            nKernel);

        if isfield(C,'ModelShort')
            assert(isequal( ...
                cellstr(string(C.ModelShort(:))).', ...
                ModelShort), ...
                'Cached EGM order differs from current manuscript order.');
        end

        if isfield(C,'KernelShort')
            assert(isequal( ...
                cellstr(string(C.KernelShort(:))).', ...
                KernelShort), ...
                'Cached kernel order differs from current manuscript order.');
        end

        Runtime = ...
            C.Runtime;

        usedExistingRuntime = ...
            true;

        fprintf('\n=============================================================\n');
        fprintf(' FAST CACHE REUSE\n');
        fprintf('=============================================================\n');
        fprintf('Loaded existing runtime MAT; source files were NOT rescanned.\n');
        fprintf('%s\n',RuntimeMAT);
        fprintf('=============================================================\n');

    catch ME

