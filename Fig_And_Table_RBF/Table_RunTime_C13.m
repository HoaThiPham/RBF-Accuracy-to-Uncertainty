                string(Names{q}); %#ok<AGROW>

            Minimum_min(end+1,1) = ...
                mn; %#ok<AGROW>

            Maximum_min(end+1,1) = ...
                mx; %#ok<AGROW>

            Range_text(end+1,1) = ...
                sprintf( ...
                    '%.2f--%.2f', ...
                    mn, ...
                    mx); %#ok<AGROW>

        end

    end

end

T = ...
    table( ...
        Case, ...
        Regime, ...
        Metric, ...
        Minimum_min, ...
        Maximum_min, ...
        Range_text);

end


%% ========================================================================
% LOCAL FUNCTION: GET RUNTIME FIELD
% ========================================================================

function M = getRuntimeField(D,candidates)

M = ...
    [];

for k = 1:numel(candidates)

    if isfield(D,candidates{k}) && ...
       ~isempty(D.(candidates{k}))

        M = ...
            double(D.(candidates{k}));

        break

    end

end

assert( ...
    ~isempty(M), ...
    'Required runtime field not found. Tried: %s', ...
    strjoin(candidates,', '));

assert( ...
    all(isfinite(M),'all') && ...
    all(M>=0,'all'), ...
    'Runtime matrix contains invalid values.');

end


%% ========================================================================
% LOCAL FUNCTION: SHORT MINUTES
% ========================================================================

function s = shortMinutes(secondsValue)

assert( ...
    isfinite(secondsValue) && ...
    secondsValue>=0, ...
    'Invalid runtime value.');

minutesValue = ...
    secondsValue / 60;

if minutesValue < 1

    s = ...
        '<1';

else

    s = ...
        sprintf( ...
            '%.0f', ...
            round(minutesValue));

end

end


