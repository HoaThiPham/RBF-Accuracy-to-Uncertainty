%% ========================================================================
% LOCAL FUNCTION: STAGE-1 WALL TIME ONLY
% ========================================================================

function [Wall_s,DiagFiles] = collectStage1WallFast( ...
    stage1Dir,stage2Dir,Models,Kernels,caseName)

nM = ...
    numel(Models);

nK = ...
    numel(Kernels);

Wall_s = ...
    nan(nM,nK);

DiagFiles = ...
    cell(nM,nK);

F2 = ...
    dir( ...
        fullfile( ...
            stage2Dir, ...
            '*_STAGE2_CORE.mat'));

F1 = ...
    dir( ...
        fullfile( ...
            stage1Dir, ...
            '*_DIAG.mat'));

assert(~isempty(F2), ...
    'No Stage2 CORE filenames:\n%s', ...
    stage2Dir);

assert(~isempty(F1), ...
    'No Stage1 DIAG files:\n%s', ...
    stage1Dir);

N2 = ...
    string({F2.name});

N1 = ...
    string({F1.name});

for i = 1:nM

    model = ...
        string(Models{i});

    for j = 1:nK

        kernel = ...
            string(Kernels{j});

        identity = ...
            "_" + ...
            model + ...
            "_" + ...
            kernel + ...
            "_";

        i2 = ...
            find( ...
                contains( ...
                    N2, ...
                    identity, ...
                    'IgnoreCase', ...
                    true));

        assert(numel(i2)==1, ...
            'Expected one Stage2 CORE filename for %s | %s | %s; found %d.', ...
            caseName, ...
            char(model), ...
            char(kernel), ...
            numel(i2));

        coreName = ...
            string(F2(i2).name);

        runField = ...
            extractBefore( ...
                coreName, ...
                "_STAGE2_CORE.mat");

        prefix = ...
            regexpPattern("^M\d+_K\d+_") + ...
            model + ...
            "_" + ...
            kernel + ...
            "_";

        tuningTag = ...
            erase( ...
                runField, ...
                prefix);

        assert( ...
            strlength(tuningTag)>0 && ...
            ~strcmp(tuningTag,runField), ...
            'Cannot parse tuning tag:\n%s', ...
            char(coreName));

        suffix = ...
            "_" + ...
            model + ...
            "_" + ...
            kernel + ...
            "_" + ...
            tuningTag + ...
            "_DIAG.mat";

        i1 = ...
            find( ...
                endsWith( ...
                    N1, ...
                    suffix, ...
                    'IgnoreCase', ...
                    true));

        assert(numel(i1)==1, ...
            ['Expected one matching Stage1 DIAG for ' ...
             '%s | %s | %s; found %d.\nSuffix: %s'], ...
            caseName, ...
            char(model), ...
            char(kernel), ...
            numel(i1), ...
            char(suffix));

        diagFile = ...
            fullfile( ...
                F1(i1).folder, ...
                F1(i1).name);

        wall = ...
            tryReadStructScalarH5( ...
                diagFile, ...
                'Stage1Diag', ...
                'stage1WallTime');

        assert( ...
            isfinite(wall) && ...
            wall>=0, ...
            'Invalid stage1WallTime:\n%s', ...
            diagFile);

        Wall_s(i,j) = ...
            wall;

        DiagFiles{i,j} = ...
            diagFile;

    end

end

end


%% ========================================================================
% LOCAL FUNCTION: BOOTSTRAP WALL TIME - FAST FIRST
% ========================================================================

function [M,readMode] = readBootstrapWallFast( ...
    fileName,Models,Kernels,label)

nM = ...
    numel(Models);

nK = ...
    numel(Kernels);

% ------------------------------------------------------------------------
% First attempt: selective HDF5 only.
% This is fastest when the saved bootstrap matrices are already 6x5.
% ------------------------------------------------------------------------

try

    try

        Mraw = ...
            readStructNumericH5( ...
                fileName, ...
                'Results', ...
                'totalWallTime');

    catch

        trainRaw = ...
            readStructNumericH5( ...
                fileName, ...
                'Results', ...
                'trainWallTime');

        testRaw = ...
            readStructNumericH5( ...
                fileName, ...
                'Results', ...
                'testWallTime');

        if isequal(size(trainRaw),size(testRaw))

            Mraw = ...
                double(trainRaw) + ...
                double(testRaw);

        else

            error( ...
                'Bootstrap train/test matrices have different sizes.');

        end

    end

    M = ...
        normalizeMatrix( ...
            Mraw, ...
            nM, ...
            nK, ...
            label);

    readMode = ...
        'selective HDF5';

    return

catch

    % A common reason is an older 7-GGM result. In that case we need the
    % saved model/kernel labels to remove the legacy GGM safely.

end

% ------------------------------------------------------------------------
% Metadata-aware fallback. Still reads SAVED Results only; no computation.
% ------------------------------------------------------------------------

R = ...
    loadResultsOnly(fileName);

if isfield(R,'totalWallTime')

    try

        M = ...
            selectCurrentMatrix( ...
                R, ...
                'totalWallTime', ...
                Models, ...
                Kernels);

    catch

        M = ...
            selectCurrentMatrix( ...
                R, ...
                'trainWallTime', ...
                Models, ...
                Kernels) + ...
            selectCurrentMatrix( ...
                R, ...
                'testWallTime', ...
                Models, ...
                Kernels);

    end

else

    M = ...
        selectCurrentMatrix( ...
            R, ...
            'trainWallTime', ...
            Models, ...
            Kernels) + ...
        selectCurrentMatrix( ...
            R, ...
            'testWallTime', ...
            Models, ...
            Kernels);

end

validateMatrix( ...
    M, ...
    nM, ...
    nK, ...
    label);

readMode = ...
    'Results metadata fallback';

end


%% ========================================================================
% LOCAL FUNCTION: SELECT CURRENT MATRIX
% ========================================================================

function Mout = selectCurrentMatrix(R,fieldName,Models,Kernels)

assert( ...
    isfield(R,fieldName), ...
    'Missing Results.%s.', ...
    fieldName);

M = ...
    double(R.(fieldName));

sourceModels = ...
    {};

sourceKernels = ...
    {};

if isfield(R,'ListOfModel') && ...
   ~isempty(R.ListOfModel)

    sourceModels = ...
        cellstr( ...
            string( ...
                R.ListOfModel(:)));

elseif isfield(R,'MatrixInfo') && ...
       isfield(R.MatrixInfo,'rows')

    sourceModels = ...
        cellstr( ...
            string( ...
                R.MatrixInfo.rows(:)));

end

if isfield(R,'NameFunction_RBF') && ...
   ~isempty(R.NameFunction_RBF)

    sourceKernels = ...
        cellstr( ...
            string( ...
                R.NameFunction_RBF(:)));

elseif isfield(R,'MatrixInfo') && ...
       isfield(R.MatrixInfo,'columns')

    sourceKernels = ...
        cellstr( ...
            string( ...
                R.MatrixInfo.columns(:)));

end

if isempty(sourceModels) && ...
   isempty(sourceKernels)

    assert( ...
        isequal( ...
            size(M), ...
            [numel(Models) numel(Kernels)]), ...
        'Unexpected matrix size for %s.', ...
        fieldName);

    Mout = ...
        M;

    return

end

assert( ...
    ~isempty(sourceModels) && ...
    ~isempty(sourceKernels), ...
    'Incomplete source matrix metadata.');

if isequal( ...
        size(M), ...
        [numel(sourceKernels) numel(sourceModels)])

    M = ...
        M.';

end

assert( ...
    isequal( ...
        size(M), ...
        [numel(sourceModels) numel(sourceKernels)]), ...
    'Matrix/metadata size mismatch for %s.', ...
    fieldName);

ri = ...
    zeros(1,numel(Models));

cj = ...
    zeros(1,numel(Kernels));

for i = 1:numel(Models)

    q = ...
        find( ...
            strcmpi( ...
                sourceModels, ...
                Models{i}), ...
            1);

    assert( ...
        ~isempty(q), ...
        'Model not found: %s', ...
        Models{i});

    ri(i) = ...
        q;

end

for j = 1:numel(Kernels)

    q = ...
        find( ...
            strcmpi( ...
                sourceKernels, ...
                Kernels{j}), ...
            1);

    assert( ...
        ~isempty(q), ...
        'Kernel not found: %s', ...
        Kernels{j});

    cj(j) = ...
        q;

end

Mout = ...
    M(ri,cj);

end


%% ========================================================================
% LOCAL FUNCTION: SELECTIVE HDF5 NUMERIC STRUCT FIELD
% ========================================================================

function value = readStructNumericH5(fileName,varName,fieldName)

fid = -1;
gid = -1;
fds = -1;
tid = -1;
vds = -1;

try

    fid = ...
        H5F.open( ...
            fileName, ...
            'H5F_ACC_RDONLY', ...
            'H5P_DEFAULT');

    gid = ...
        H5G.open( ...
            fid, ...
            ['/' varName]);

    fds = ...
        H5D.open( ...
            gid, ...
            fieldName);

    tid = ...
        H5D.get_type(fds);

    typeClass = ...
        H5T.get_class(tid);

    refClass = ...
        H5ML.get_constant_value( ...
            'H5T_REFERENCE');

    if isequal(typeClass,refClass)

        refs = ...
            H5D.read(fds);

        assert( ...
            ~isempty(refs), ...
            'Empty HDF5 reference: %s.%s', ...
            varName, ...
            fieldName);

        if iscell(refs)

            ref = ...
                refs{1};

        else

            ref = ...
                refs(:,1);

        end

        vds = ...
            H5R.dereference( ...
                fds, ...
                'H5R_OBJECT', ...
                ref);

        value = ...
            H5D.read(vds);

    else

        value = ...
            H5D.read(fds);

    end

    if vds >= 0
        H5D.close(vds);
        vds = -1;
    end

    H5T.close(tid);
    tid = -1;

    H5D.close(fds);
    fds = -1;

    H5G.close(gid);
    gid = -1;

    H5F.close(fid);
    fid = -1;

catch ME

    if vds >= 0
        try H5D.close(vds); catch, end
    end

    if tid >= 0
        try H5T.close(tid); catch, end
    end

    if fds >= 0
        try H5D.close(fds); catch, end
    end

    if gid >= 0
        try H5G.close(gid); catch, end
    end

    if fid >= 0
        try H5F.close(fid); catch, end
    end

    error( ...
        ['Selective HDF5 read failed:\n%s\n' ...
         'Field: %s.%s\n\n%s'], ...
        fileName, ...
        varName, ...
        fieldName, ...
        ME.message);

end

assert( ...
    isnumeric(value) && ...
    isreal(value), ...
    'Non-numeric field: %s.%s', ...
    varName, ...
    fieldName);

value = ...
    double(value);

end


