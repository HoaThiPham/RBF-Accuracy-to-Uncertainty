%% ========================================================================
% GATHER TQ METRICS
%
% Gather BEFORE-calibration:
%   RMSE
%   ASE
%   RMSSE
%
% for:
%   Case 1 / Case 2
%   Global / Local
%   Train / Test
%
% Kriging will be added later.
% ========================================================================

clear
clc


%% ========================================================================
% 1. USER INPUT
% ========================================================================

RootDir = '.';


% ------------------------------------------------------------------------
% GLOBAL CALIBRATION
% ------------------------------------------------------------------------

GlobalFileCase1 = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026', ...
        'Case1_NonSpatialVarianceCalibration.mat');

GlobalFileCase2 = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026', ...
        'Case2_NonSpatialVarianceCalibration.mat');


% ------------------------------------------------------------------------
% LOCAL CALIBRATION
% ------------------------------------------------------------------------

LocalDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'LocalVarianceCalibration_pseudo_unseen_B200_S0');

LocalFileCase1 = ...
    fullfile( ...
        LocalDir, ...
        'Case1_Local_VarianceCalibration.mat');

LocalFileCase2 = ...
    fullfile( ...
        LocalDir, ...
        'Case2_Local_VarianceCalibration.mat');


% ------------------------------------------------------------------------
% OUTPUT
% ------------------------------------------------------------------------

OutputDir = ...
    fullfile( ...
        RootDir, ...
        'OutPut_RBF_2026_2', ...
        'TQ');

OutputFile = ...
    fullfile( ...
        OutputDir, ...
        'RMSE_ASE_RMSSE_BeforeCalibration_Metrix.mat');


%% ========================================================================
% 2. MODELS AND KERNELS
%
% SGG1 is not included.
% ========================================================================

Models = { ...
    'EGM2008', ...
    'ggmplus', ...
    'eigen6c4', ...
    'geco', ...
    'sgg2', ...
    'xgm19'};

ModelShort = { ...
    'E08', ...
    'GGP', ...
    'EC4', ...
    'GCO', ...
    'SG2', ...
    'X19'};

Kernels = { ...
    'gaussian', ...
    'multiquadric', ...
    'thinplate', ...
    'cubic', ...
    'linear'};

KernelShort = { ...
    'G', ...
    'M', ...
    'T', ...
    'C', ...
    'L'};


nModel = ...
    numel(Models);

nKernel = ...
    numel(Kernels);


%% ========================================================================
% 3. LOAD FINAL CALIBRATION RESULTS
% ========================================================================

S = ...
    load( ...
        GlobalFileCase1, ...
        'Results');

GlobalCase1 = ...
    S.Results;

clear S


S = ...
    load( ...
        GlobalFileCase2, ...
        'Results');

GlobalCase2 = ...
    S.Results;

clear S


S = ...
    load( ...
        LocalFileCase1, ...
        'Results');

LocalCase1 = ...
    S.Results;

clear S


S = ...
    load( ...
        LocalFileCase2, ...
        'Results');

LocalCase2 = ...
    S.Results;

clear S


%% ========================================================================
% 4. INITIALISE MATRICES
%
% rows    = EGM models
% columns = RBF kernels
% ========================================================================

RMSE_ASE_RMSSE_Metrix = ...
    struct();


Phases = { ...
    'Train', ...
    'Test'};

Cases = { ...
    'Case1', ...
    'Case2'};

Regimes = { ...
    'Global', ...
    'Local'};


for ip = 1:numel(Phases)

    for ic = 1:numel(Cases)

        for ir = 1:numel(Regimes)

            RMSE_ASE_RMSSE_Metrix.(Phases{ip}). ...
                (Cases{ic}). ...
                (Regimes{ir}).RMSE = ...
                nan(nModel,nKernel);

            RMSE_ASE_RMSSE_Metrix.(Phases{ip}). ...
                (Cases{ic}). ...
                (Regimes{ir}).ASE = ...
                nan(nModel,nKernel);

            RMSE_ASE_RMSSE_Metrix.(Phases{ip}). ...
                (Cases{ic}). ...
                (Regimes{ir}).RMSSE = ...
                nan(nModel,nKernel);

        end

    end

end


%% ========================================================================
% 5. GATHER GLOBAL + LOCAL
% ========================================================================

Source = { ...
    GlobalCase1, 'Case1', 'Global'; ...
    GlobalCase2, 'Case2', 'Global'; ...
    LocalCase1,  'Case1', 'Local'; ...
    LocalCase2,  'Case2', 'Local'};


for isource = 1:size(Source,1)

    Results = ...
        Source{isource,1};

    CaseName = ...
        Source{isource,2};

    Regime = ...
        Source{isource,3};


    for i = 1:nModel

        for j = 1:nKernel

            runName = ...
                [Models{i} '_' Kernels{j}];

            assert( ...
                isfield(Results.Run,runName), ...
                'Missing run: %s', ...
                runName);

            R = ...
                Results.Run.(runName);


            % -------------------------------------------------------------
            % TRAIN
            % -------------------------------------------------------------

            RMSE_ASE_RMSSE_Metrix.Train.(CaseName).(Regime).RMSE(i,j) = ...
                R.Train.RMSE;

            RMSE_ASE_RMSSE_Metrix.Train.(CaseName).(Regime).ASE(i,j) = ...
                R.Train.ASE_Pre;

            RMSE_ASE_RMSSE_Metrix.Train.(CaseName).(Regime).RMSSE(i,j) = ...
                R.Train.RMSSE_Pre;


            % -------------------------------------------------------------
            % TEST
            % -------------------------------------------------------------

            RMSE_ASE_RMSSE_Metrix.Test.(CaseName).(Regime).RMSE(i,j) = ...
                R.Test.RMSE;

            RMSE_ASE_RMSSE_Metrix.Test.(CaseName).(Regime).ASE(i,j) = ...
                R.Test.ASE_Pre;

            RMSE_ASE_RMSSE_Metrix.Test.(CaseName).(Regime).RMSSE(i,j) = ...
                R.Test.RMSSE_Pre;

        end

    end

end


%% ========================================================================
% 6. LABELS
% ========================================================================

RMSE_ASE_RMSSE_Metrix.Models = ...
    Models;

RMSE_ASE_RMSSE_Metrix.ModelShort = ...
    ModelShort;

RMSE_ASE_RMSSE_Metrix.Kernels = ...
    Kernels;

RMSE_ASE_RMSSE_Metrix.KernelShort = ...
    KernelShort;


RMSE_ASE_RMSSE_Metrix.CalibrationState = ...
    'Before calibration';

RMSE_ASE_RMSSE_Metrix.SourceFields = ...
    struct( ...
        'RMSE','RMSE', ...
        'ASE','ASE_Pre', ...
        'RMSSE','RMSSE_Pre');


