% 14. GATHER RBF
%
% VarianceCalibrated ONLY.
% ========================================================================

RBFSource = { ...
    GlobalCase1, 'Case1', 'Global'; ...
    LocalCase1,  'Case1', 'Local'; ...
    GlobalCase2, 'Case2', 'Global'; ...
    LocalCase2,  'Case2', 'Local'};




for isource = 1:size(RBFSource,1)

    Results = ...
        RBFSource{isource,1};


    CaseName = ...
        RBFSource{isource,2};


    Regime = ...
        RBFSource{isource,3};


    for i = 1:nModel

        for j = 1:nRBF

            runName = ...
                [ListOfModel{i} '_' RBFKernels{j}];


            assert( ...
                isfield(Results.Run,runName), ...
                'Missing RBF run: %s %s %s', ...
                CaseName,Regime,runName);


            R = ...
                Results.Run.(runName);


            %% ------------------------------------------------------------
            % TRAIN
            % -------------------------------------------------------------

            assert( ...
                isfield(R,'Train') && ...
                isfield(R.Train,'VarianceCalibrated'), ...
                ['Missing calibrated RBF variance: ' ...
                 '%s %s %s Train'], ...
                CaseName,Regime,runName);


            V = ...
                R.Train.VarianceCalibrated(:);


            SpatialVariance. ...
                (CaseName). ...
                (Regime). ...
                Train. ...
                (runName).Variance = ...
                V;


            %% ------------------------------------------------------------
            % TEST
            % -------------------------------------------------------------

            assert( ...
                isfield(R,'Test') && ...
                isfield(R.Test,'VarianceCalibrated'), ...
                ['Missing calibrated RBF variance: ' ...
                 '%s %s %s Test'], ...
                CaseName,Regime,runName);


            V = ...
                R.Test.VarianceCalibrated(:);


            SpatialVariance. ...
                (CaseName). ...
                (Regime). ...
                Test. ...
                (runName).Variance = ...
                V;

        end

    end

end


