% 16. VALIDATE FINAL DATASET
%
% 2 cases
% x 2 regimes
% x 2 phases
% x 6 EGMs
% x 6 methods
% = 288 vectors
% ========================================================================

CheckSets = { ...
    SpatialVariance.Case1.Global.Train, ...
    numel(Coordinates.Case1.Train.X), ...
    'Case 1 Global Train'; ...

    SpatialVariance.Case1.Global.Test, ...
    numel(Coordinates.Case1.Test.X), ...
    'Case 1 Global Test'; ...

    SpatialVariance.Case1.Local.Train, ...
    numel(Coordinates.Case1.Train.X), ...
    'Case 1 Local Train'; ...

    SpatialVariance.Case1.Local.Test, ...
    numel(Coordinates.Case1.Test.X), ...
    'Case 1 Local Test'; ...

    SpatialVariance.Case2.Global.Train, ...
    numel(Coordinates.Case2.Train.X), ...
    'Case 2 Global Train'; ...

    SpatialVariance.Case2.Global.Test, ...
    numel(Coordinates.Case2.Test.X), ...
    'Case 2 Global Test'; ...

    SpatialVariance.Case2.Local.Train, ...
    numel(Coordinates.Case2.Train.X), ...
    'Case 2 Local Train'; ...

    SpatialVariance.Case2.Local.Test, ...
    numel(Coordinates.Case2.Test.X), ...
    'Case 2 Local Test'};


NumberVectors = ...
    0;


for id = 1:size(CheckSets,1)

    D = ...
        CheckSets{id,1};


    ExpectedN = ...
        CheckSets{id,2};


    Label = ...
        CheckSets{id,3};


    for i = 1:nModel

        for j = 1:nMethod

            runName = ...
                [ListOfModel{i} '_' ListFunction{j}];


            assert( ...
                isfield(D,runName), ...
                '%s missing %s.', ...
                Label,runName);


            V = ...
                D.(runName).Variance(:);


            assert( ...
                numel(V) == ExpectedN, ...
                ['Length mismatch: %s | %s\n' ...
                 'Variance = %d, expected = %d'], ...
                Label,runName,numel(V),ExpectedN);


            assert( ...
                all(isfinite(V)), ...
                '%s | %s contains NaN/Inf.', ...
                Label,runName);


            assert( ...
                all(V >= 0), ...
                '%s | %s contains negative variance.', ...
                Label,runName);


            NumberVectors = ...
                NumberVectors + 1;

        end

    end

end


assert( ...
    NumberVectors == 288, ...
    'Expected 288 vectors; found %d.', ...
    NumberVectors);


