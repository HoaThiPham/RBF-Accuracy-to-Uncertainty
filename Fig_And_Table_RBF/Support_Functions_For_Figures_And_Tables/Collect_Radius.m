function Index = buildStage2CoreIndex( ...
    Stage2Dir, ...
    ExpectedCase, ...
    ListOfModel, ...
    ListFunction)

Files = ...
    dir( ...
        fullfile( ...
            Stage2Dir, ...
            '*.mat'));


assert( ...
    ~isempty(Files), ...
    'No MAT files found in:\n%s', ...
    Stage2Dir);


Index = ...
    struct();


for q = 1:numel(Files)

    FilePath = ...
        fullfile( ...
            Files(q).folder, ...
            Files(q).name);


    try

        W = ...
            whos( ...
                '-file', ...
                FilePath);

    catch

        continue

    end


    if ~ismember( ...
            'Stage2Core', ...
            {W.name})

        continue

    end


    S = ...
        load( ...
            FilePath, ...
            'Stage2Core');


    if ~isfield(S,'Stage2Core') || ...
       ~isstruct(S.Stage2Core)

        continue

    end


    Core = ...
        S.Stage2Core;


    clear S


    %% --------------------------------------------------------------------
    % Only completed commits
    % ---------------------------------------------------------------------

    if ~isfield(Core,'Storage') || ...
       ~isstruct(Core.Storage) || ...
       ~isfield(Core.Storage,'Complete') || ...
       ~logical(Core.Storage.Complete)

        continue

    end


    %% --------------------------------------------------------------------
    % Setup identity
    % ---------------------------------------------------------------------

    if ~isfield(Core,'Setup') || ...
       ~isstruct(Core.Setup) || ...
       ~isfield(Core.Setup,'Model') || ...
       ~isfield(Core.Setup,'Kernel')

        continue

    end


    modelName = ...
        char(string(Core.Setup.Model));


    kernelName = ...
        char(string(Core.Setup.Kernel));


    if isfield(Core.Setup,'Case') && ...
       ~isempty(Core.Setup.Case)

        coreCase = ...
            char(string(Core.Setup.Case));


        if ~strcmpi(coreCase,ExpectedCase)

            continue

        end

    end


    iModel = ...
        find( ...
            strcmpi( ...
                ListOfModel, ...
                modelName), ...
            1);


    iKernel = ...
        find( ...
            strcmpi( ...
                ListFunction, ...
                kernelName), ...
            1);


    if isempty(iModel) || ...
       isempty(iKernel)

        continue

    end


    %% --------------------------------------------------------------------
    % Require authoritative Train/Test radius
    % ---------------------------------------------------------------------

    if ~isfield(Core,'Parameters') || ...
       ~isstruct(Core.Parameters) || ...
       ~isfield(Core.Parameters,'Train') || ...
       ~isstruct(Core.Parameters.Train) || ...
       ~isfield(Core.Parameters.Train,'Radius') || ...
       ~isfield(Core.Parameters,'Test') || ...
       ~isstruct(Core.Parameters.Test) || ...
       ~isfield(Core.Parameters.Test,'Radius')

        continue

    end


    runName = ...
        [ ...
        ListOfModel{iModel} ...
        '_' ...
        ListFunction{iKernel} ...
        ];


    assert( ...
        ~isfield(Index,runName), ...
        'Duplicate completed Stage2Core for %s in:\n%s', ...
        runName, ...
        Stage2Dir);


    Index.(runName) = ...
        FilePath;

end


%% ------------------------------------------------------------------------
% Require complete current 6 x 5 set
% -------------------------------------------------------------------------

for i = 1:numel(ListOfModel)

    for j = 1:numel(ListFunction)

        runName = ...
            [ListOfModel{i} '_' ListFunction{j}];


        assert( ...
            isfield(Index,runName), ...
            'Missing completed Stage2Core for %s in:\n%s', ...
            runName, ...
            Stage2Dir);

    end

end

end


% =========================================================================
function [TrainOut,TestOut,MaxTrain,MaxTest] = collectOneCase( ...
    CoreIndex, ...
    nTrain, ...
    nTest, ...
    ListOfModel, ...
    ListFunction)

nModel = ...
    numel(ListOfModel);


nKernel = ...
    numel(ListFunction);


TrainOut = ...
    struct();


TestOut = ...
    struct();


MaxTrain = ...
    nan(nModel,nKernel);


MaxTest = ...
    nan(nModel,nKernel);


for i = 1:nModel

    for j = 1:nKernel

        runName = ...
            [ListOfModel{i} '_' ListFunction{j}];


        CoreFile = ...
            CoreIndex.(runName);


        S = ...
            load( ...
                CoreFile, ...
                'Stage2Core');


        assert( ...
            isfield(S,'Stage2Core') && ...
            isstruct(S.Stage2Core), ...
            'Invalid Stage2Core:\n%s', ...
            CoreFile);


        Core = ...
            S.Stage2Core;


        clear S


        assert( ...
            isfield(Core,'Storage') && ...
            isstruct(Core.Storage) && ...
            isfield(Core.Storage,'Complete') && ...
            logical(Core.Storage.Complete), ...
            'Stage2Core is not a completed commit:\n%s', ...
            CoreFile);


        RadiusTrain_m = ...
            Core.Parameters.Train.Radius(:);


        RadiusTest_m = ...
            Core.Parameters.Test.Radius(:);


        assert( ...
            numel(RadiusTrain_m) == nTrain, ...
            ['Train radius length mismatch for %s.\n' ...
             'Radius = %d, coordinates = %d'], ...
            runName, ...
            numel(RadiusTrain_m), ...
            nTrain);


        assert( ...
            numel(RadiusTest_m) == nTest, ...
            ['Test radius length mismatch for %s.\n' ...
             'Radius = %d, coordinates = %d'], ...
            runName, ...
            numel(RadiusTest_m), ...
            nTest);


        assert( ...
            all(isfinite(RadiusTrain_m)) && ...
            all(RadiusTrain_m > 0), ...
            'Invalid Train radius: %s.', ...
            runName);


        assert( ...
            all(isfinite(RadiusTest_m)) && ...
            all(RadiusTest_m > 0), ...
            'Invalid Test radius: %s.', ...
            runName);


        RadiusTrain_km = ...
            RadiusTrain_m ./ 1000;


        RadiusTest_km = ...
            RadiusTest_m ./ 1000;


        TrainOut.(runName).Radius_km = ...
            RadiusTrain_km;


        TestOut.(runName).Radius_km = ...
            RadiusTest_km;


        MaxTrain(i,j) = ...
            max(RadiusTrain_km);


        MaxTest(i,j) = ...
            max(RadiusTest_km);

    end

end

