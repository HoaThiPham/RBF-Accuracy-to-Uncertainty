%% ========================================================================
% LOCAL SUBPLOT LAYOUT FUNCTION
%
% Embedded local subplot-layout helper.
% The arguments preserve the original layout convention:
%   gap    = [vertical horizontal]
%   marg_h = [bottom top]
%   marg_w = [left right]
% ========================================================================

function [ha, pos] = compact_subplot(Nh, Nw, gap, marg_h, marg_w)
%COMPACT_SUBPLOT Create a compact grid of axes with configurable spacing.
%
%   [HA, POS] = COMPACT_SUBPLOT(NH, NW, GAP, MARG_H, MARG_W)
%
%   Inputs
%   ------
%   NH      Number of axes rows.
%   NW      Number of axes columns.
%
%   GAP     Spacing between adjacent axes, in normalized figure units.
%           A scalar applies the same spacing vertically and horizontally.
%           A two-element vector is interpreted as:
%               [vertical_gap horizontal_gap]
%
%   MARG_H  Vertical margins in normalized figure units.
%           A scalar applies the same lower and upper margin.
%           A two-element vector is interpreted as:
%               [lower_margin upper_margin]
%
%   MARG_W  Horizontal margins in normalized figure units.
%           A scalar applies the same left and right margin.
%           A two-element vector is interpreted as:
%               [left_margin right_margin]
%
%   Outputs
%   -------
%   HA      Column vector containing axes handles. Axes are ordered
%           row-by-row, starting from the upper-left corner.
%
%   POS     Axes positions returned by MATLAB when requested.
%
%   This implementation preserves the original layout logic while using
%   clearer variable names and comments.

%% Default settings

if nargin < 3
    gap = 0.02;
end

if nargin < 4 || isempty(marg_h)
    marg_h = 0.05;
end

if nargin < 5
    marg_w = 0.05;
end

%% Expand scalar settings to two-element vectors

if numel(gap) == 1
    gap = [gap gap];
end

if numel(marg_h) == 1
    marg_h = [marg_h marg_h];
end

if numel(marg_w) == 1
    marg_w = [marg_w marg_w];
end

%% Compute axes dimensions

axesHeight = ...
    (1 - sum(marg_h) - (Nh - 1) * gap(1)) / Nh;

axesWidth = ...
    (1 - sum(marg_w) - (Nw - 1) * gap(2)) / Nw;

%% Create axes from upper-left to lower-right

currentY = ...
    1 - marg_h(2) - axesHeight;

ha = ...
    gobjects(Nh * Nw,1);

panelIndex = ...
    0;

for rowIndex = 1:Nh

    currentX = ...
        marg_w(1);

    for colIndex = 1:Nw

        panelIndex = ...
            panelIndex + 1;

        ha(panelIndex) = ...
            axes( ...
                'Units','normalized', ...
                'Position',[currentX currentY axesWidth axesHeight], ...
                'XTickLabel','', ...
                'YTickLabel','');

        currentX = ...
            currentX + axesWidth + gap(2);

    end

    currentY = ...
        currentY - axesHeight - gap(1);

end

%% Return positions when requested

if nargout > 1
    pos = ...
        get(ha,'Position');
end

ha = ...
    ha(:);

end

%% ========================================================================
% LOCAL FUNCTION: FigBar
%
% Embedded grouped-bar plotting helper.
% ========================================================================

function FigBar( ...
    X, ...
    Data, ...
    ylabelName, ...
    xlabelName, ...
    X_label, ...
    yLim, ...
    xText, ...
    yText, ...
    Text1, ...
    Text2, ...
    Text3, ...
    FontSize_Text, ...
    FontSize_Xaxis, ...
    Legend, ...
    LegendValue)

% ========================================================================
% COMMON GROUPED-BAR FUNCTION
%
% Rows:
%   E08, GGP, EC4, GCO, SG2, X19
%
% Columns:
%   1 Rbf-G
%   2 Rbf-M
%   3 Rbf-T
%   4 Rbf-C
%   5 Rbf-L
%   6 Kriging-S
% ========================================================================


%% ========================================================================
% 1. FONT
% ========================================================================

FontName = ...
    'Times New Roman';


%% ========================================================================
% 2. CHECK INPUT
% ========================================================================

nBar = ...
    size(Data,2);


if numel(Legend) ~= nBar

    error( ...
        ['Number of legend entries (%d) must equal ' ...
         'number of Data columns (%d).'], ...
        numel(Legend), ...
        nBar);

end


%% ========================================================================
% 3. COLORS
% ========================================================================

Color = ...
    [ ...
    0.25  0.40  0.60; ...
    0.70  0.50  0.65; ...
    0.10  0.55  0.20; ...
    0.35  0.40  0.75; ...
    0.45  0.50  0.40; ...
    0.20  0.65  0.80  ...
    ];


if nBar > size(Color,1)

    error( ...
        'FigBar supports a maximum of %d bar series.', ...
        size(Color,1));

end


%% ========================================================================
% 4. BAR PLOT
% ========================================================================

b = ...
    bar( ...
        X, ...
        Data, ...
        'grouped');


hold on


%% ========================================================================
% 5. BAR COLORS
% ========================================================================

for k = 1:nBar

    b(k).FaceColor = ...
        Color(k,:);

end


%% ========================================================================
% 6. AXIS
% ========================================================================

ylim( ...
    yLim);


set( ...
    gca, ...
    'FontName', ...
    FontName, ...
    'FontSize', ...
    FontSize_Xaxis, ...
    'LineWidth', ...
    0.8, ...
    'TickDir', ...
    'in');


box on


%% ========================================================================
% 7. Y LABEL
% ========================================================================

if ~isempty(ylabelName)

    ylabel( ...
        ylabelName, ...
        'FontName', ...
        FontName, ...
        'FontSize', ...
        FontSize_Text);

end


%% ========================================================================
% 8. X LABEL
% ========================================================================

if X_label == 1

    xlabel( ...
        xlabelName, ...
        'FontName', ...
        FontName, ...
        'FontSize', ...
        FontSize_Text);

end


%% ========================================================================
% 9. PANEL TITLE
% ========================================================================

if iscell(Text1)

    Text1 = ...
        Text1{1};

end


if iscell(Text2)

    Text2 = ...
        Text2{1};

end


if iscell(Text3)

    Text3 = ...
        Text3{1};

end


PanelText = ...
    [ ...
    char(Text1), ...
    char(Text2), ...
    char(Text3) ...
    ];


text( ...
    0.10, ...
    0.965, ...
    PanelText, ...
    'Units', ...
    'normalized', ...
    'FontName', ...
    FontName, ...
    'FontSize', ...
    FontSize_Text, ...
    'HorizontalAlignment', ...
    'left', ...
    'VerticalAlignment', ...
    'top');


%% ========================================================================
% 10. LEGEND
% ========================================================================

if LegendValue == 1

    lgd = ...
        legend( ...
            b, ...
            Legend, ...
            'Orientation', ...
            'horizontal');


    set( ...
        lgd, ...
        'FontName', ...
        FontName, ...
        'FontSize', ...
        11, ...
        'Units', ...
        'normalized', ...
        'Box', ...
        'on');


    set( ...
        lgd, ...
        'Position', ...
        [0.185 0.020 0.63 0.035]);

end


%% ========================================================================
% 11. FINAL FONT
% ========================================================================

set( ...
    gca, ...
    'FontName', ...
    FontName);


hold off

end