    xlabel( ...
        xlabelName, ...
        'FontName', ...
        FontName, ...
        'FontSize', ...
        FontSize_Text);

end


%% ========================================================================
% 9. PANEL TITLE
% ========================================================================

if iscell(Text1)

    Text1 = ...
        Text1{1};

end


if iscell(Text2)

    Text2 = ...
        Text2{1};

end


if iscell(Text3)

