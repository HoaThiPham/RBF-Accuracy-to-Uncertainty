% ========================================================================

b = ...
    bar( ...
        X, ...
        Data, ...
        'grouped');


hold on


%% ========================================================================
% 5. BAR COLORS
% ========================================================================

for k = 1:nBar

    b(k).FaceColor = ...
        Color(k,:);

end


%% ========================================================================
% 6. AXIS
% ========================================================================

ylim( ...
    yLim);


set( ...
    gca, ...
    'FontName', ...
    FontName, ...
    'FontSize', ...
    FontSize_Xaxis, ...
    'LineWidth', ...
    0.8, ...
    'TickDir', ...
    'in');


box on


