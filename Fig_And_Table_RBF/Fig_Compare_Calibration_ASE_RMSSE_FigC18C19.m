% =========================================================================
function T = ...
    buildOverallCalibrationNumbers( ...
        Comparison, ...
        PhaseList, ...
        Cases, ...
        Regimes)
%BUILDOVERALLCALIBRATIONNUMBERS
%
% Pool configuration-level values over the requested phases and report:
%
%   raw diagnostic before: min / median / max
%   raw diagnostic after : min / median / max
%   number improved according to distance from target 1
%
% This is intended to provide the exact manuscript numbers for:
%
%   ASE/RMSE
%   RMSSE

aseBefore = ...
    [];


aseAfter = ...
    [];


aseImprove = ...
    [];


rmsseBefore = ...
    [];


rmsseAfter = ...
    [];


rmsseImprove = ...
    [];


for ip = 1:numel(PhaseList)

    Phase = ...
        PhaseList{ip};


    for ic = 1:numel(Cases)

        CaseName = ...
            Cases{ic};


        for ir = 1:numel(Regimes)

            Regime = ...
                Regimes{ir};


            D = ...
                Comparison.(Phase). ...
                    (CaseName). ...
                    (Regime).Detail;


            aseBefore = ...
                [ ...
                aseBefore; ...
                D.ASERatio_Before(:) ...
                ]; %#ok<AGROW>


            aseAfter = ...
                [ ...
                aseAfter; ...
                D.ASERatio_After(:) ...
                ]; %#ok<AGROW>


            aseImprove = ...
                [ ...
                aseImprove; ...
                D.ASERatioImprovement(:) ...
                ]; %#ok<AGROW>


            rmsseBefore = ...
                [ ...
                rmsseBefore; ...
                D.RMSSE_Before(:) ...
                ]; %#ok<AGROW>


            rmsseAfter = ...
                [ ...
                rmsseAfter; ...
                D.RMSSE_After(:) ...
                ]; %#ok<AGROW>


            rmsseImprove = ...
                [ ...
                rmsseImprove; ...
                D.RMSSEImprovement(:) ...
                ]; %#ok<AGROW>

        end

    end

end


[AseBeforeMin,AseBeforeMedian,AseBeforeMax,AseBeforeN] = ...
    minMedianMaxFinite( ...
        aseBefore);


[AseAfterMin,AseAfterMedian,AseAfterMax,AseAfterN] = ...
    minMedianMaxFinite( ...
        aseAfter);


[RmsseBeforeMin,RmsseBeforeMedian,RmsseBeforeMax,RmsseBeforeN] = ...
    minMedianMaxFinite( ...
        rmsseBefore);


[RmsseAfterMin,RmsseAfterMedian,RmsseAfterMax,RmsseAfterN] = ...
    minMedianMaxFinite( ...
        rmsseAfter);


aseValidImprove = ...
    isfinite(aseImprove);


rmsseValidImprove = ...
    isfinite(rmsseImprove);


aseImprovedN = ...
    nnz( ...
        aseImprove(aseValidImprove) > 0);


rmsseImprovedN = ...
    nnz( ...
        rmsseImprove(rmsseValidImprove) > 0);


Metric = ...
    [ ...
    "ASE/RMSE"; ...
    "RMSSE" ...
    ];


BeforeMin = ...
    [ ...
    AseBeforeMin; ...
    RmsseBeforeMin ...
    ];


BeforeMedian = ...
    [ ...
    AseBeforeMedian; ...
    RmsseBeforeMedian ...
    ];


BeforeMax = ...
    [ ...
    AseBeforeMax; ...
    RmsseBeforeMax ...
    ];


AfterMin = ...
    [ ...
    AseAfterMin; ...
    RmsseAfterMin ...
    ];


AfterMedian = ...
    [ ...
    AseAfterMedian; ...
    RmsseAfterMedian ...
    ];


AfterMax = ...
    [ ...
    AseAfterMax; ...
    RmsseAfterMax ...
    ];


ImprovedN = ...
    [ ...
    aseImprovedN; ...
    rmsseImprovedN ...
    ];


ValidN = ...
    [ ...
    nnz(aseValidImprove); ...
    nnz(rmsseValidImprove) ...
    ];


BeforeN = ...
    [ ...
    AseBeforeN; ...
    RmsseBeforeN ...
    ];


AfterN = ...
    [ ...
    AseAfterN; ...
    RmsseAfterN ...
    ];


ImprovedPct = ...
    100 .* ...
    ImprovedN ./ ...
    ValidN;


T = ...
    table( ...
        Metric, ...
        BeforeMin, ...
        BeforeMedian, ...
        BeforeMax, ...
        AfterMin, ...
        AfterMedian, ...
        AfterMax, ...
        ImprovedN, ...
        ValidN, ...
        ImprovedPct, ...
        BeforeN, ...
        AfterN);

end


