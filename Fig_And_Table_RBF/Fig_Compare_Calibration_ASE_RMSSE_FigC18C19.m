function createASEOverRMSEFigure( ...
    Comparison, ...
    Cases, ...
    Regimes, ...
    Phases, ...
    outputBase)

fig = ...
    figure( ...
        'Visible','off', ...
        'Color','w', ...
        'Units','pixels', ...
        'Position',[100 100 1800 1350]);


tl = ...
    tiledlayout( ...
        fig, ...
        4, ...
        2, ...
        'TileSpacing','compact', ...
        'Padding','compact');


title( ...
    tl, ...
    'ASE/RMSE before and after calibration', ...
    'FontWeight','bold');


block = ...
    0;


for ic = 1:numel(Cases)

    for ir = 1:numel(Regimes)

        for ip = 1:numel(Phases)

            block = ...
                block + 1;


            CaseName = ...
                Cases{ic};


            Regime = ...
                Regimes{ir};


            Phase = ...
                Phases{ip};


            D = ...
                Comparison.(Phase). ...
                    (CaseName). ...
                    (Regime).Detail;


            x = ...
                (1:height(D)).';


            ratioBefore = ...
                D.ASE_Before ./ ...
                D.RMSE;


            ratioAfter = ...
                D.ASE_After ./ ...
                D.RMSE;


            ax = ...
                nexttile( ...
                    tl, ...
                    block);


            hold( ...
                ax, ...
                'on');


            h1 = ...
                plot( ...
                    ax, ...
                    x, ...
                    ratioBefore, ...
                    '-o', ...
                    'LineWidth',1.0, ...
                    'MarkerSize',3);


            h2 = ...
                plot( ...
                    ax, ...
                    x, ...
                    ratioAfter, ...
                    '-s', ...
                    'LineWidth',1.0, ...
                    'MarkerSize',3);


            hTarget = ...
                yline( ...
                    ax, ...
                    1, ...
                    '--', ...
                    'Target = 1', ...
                    'LineWidth',1.0);


            grid( ...
                ax, ...
                'on');


            box( ...
                ax, ...
                'on');


            xlim( ...
                ax, ...
                [1 height(D)]);


            title( ...
                ax, ...
                makePanelTitle( ...
                    CaseName, ...
                    Regime, ...
                    Phase), ...
                'FontWeight','normal');


            ylabel( ...
                ax, ...
                'ASE / RMSE');


            addModelSeparators( ...
                ax, ...
                height(D));


            setConfigurationTicks( ...
                ax, ...
                D, ...
                block > 6);


            if block <= 6

                set( ...
                    ax, ...
                    'XTickLabel',[]);

            end


            if block == 1

                legend( ...
                    ax, ...
                    [h1 h2 hTarget], ...
                    {'Before','After','Ideal target'}, ...
                    'Location','best', ...
                    'Box','off');

            end


            hold( ...
                ax, ...
                'off');

        end

    end

end


xlabel( ...
    tl, ...
    'Model-kernel configuration');


ylabel( ...
    tl, ...
    'ASE/RMSE');


exportFigureAllFormats( ...
    fig, ...
    outputBase);


close(fig);

end


