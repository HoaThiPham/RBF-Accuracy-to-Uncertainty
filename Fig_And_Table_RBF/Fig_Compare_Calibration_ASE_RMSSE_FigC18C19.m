% Fig_Compare_Calibration_ASE_RMSSE_FigC18C19
%
% Compare BEFORE vs AFTER variance calibration and export:
%
%   1) Excel workbook
%   2) LaTeX tables
%
% Comparison quantities:
%
%   RMSE
%   ASE before / after
%   ASE - RMSE before / after
%   |ASE - RMSE| before / after
%   ASE-gap improvement
%
%   RMSSE before / after
%   RMSSE - 1 before / after
%   |RMSSE - 1| before / after
%   RMSSE improvement
%
% Positive improvement means calibration moved the uncertainty diagnostic
% CLOSER to its target:
%
%   ASE target   : RMSE
%   RMSSE target : 1
%
% RMSE is expected to be unchanged by variance calibration and is checked
% automatically for every Case x Regime x Phase x Model x Kernel.
%
% INPUT FILES
% -------------------------------------------------------------------------
% AFTER calibration:
%   RMSE_ASE_RMSSE_Metrix.mat
%
% BEFORE calibration:
%   RMSE_ASE_RMSSE_BeforeCalibration_Metrix.mat
%
% Both files must contain:
%   RMSE_ASE_RMSSE_Metrix
%
% with the same structure:
%
%   .Train/.Test
%       .Case1/.Case2
%           .Global/.Local
%               .RMSE
%               .ASE
%               .RMSSE
%
% OUTPUT
% -------------------------------------------------------------------------
% Excel:
%   Calibration_ASE_RMSSE_Comparison.xlsx
%
%   Sheets:
%       Summary
%       C1_G_Train
%       C1_G_Test
%       C1_L_Train
%       C1_L_Test
%       C2_G_Train
%       C2_G_Test
%       C2_L_Train
%       C2_L_Test
%
% LaTeX:
%   Calibration_ASE_RMSSE_Comparison.tex
%
%   Contains:
%       one summary table
%       eight detailed tables
%
% The LaTeX file is a fragment.  The manuscript preamble should include:
%
%   \usepackage{booktabs}
%   \usepackage{graphicx}
%
% ========================================================================

