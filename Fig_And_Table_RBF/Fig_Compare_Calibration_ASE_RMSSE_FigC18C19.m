% =========================================================================
function D = ...
    getMetricBlock( ...
        M, ...
        Phase, ...
        CaseName, ...
        Regime, ...
        Models, ...
        Kernels, ...
        label)
%GETMETRICBLOCK
%
% Return the CURRENT 6-model x 5-kernel block even when the saved metric
% file contains an older/larger model list or a transposed matrix.
%
% Selection uses the source file's own labels:
%
%   M.Models
%   M.Kernels
%
% whenever they are available.  Therefore an older file that still
% contains SGG1, for example, is safely reduced to the current manuscript
% order instead of failing merely because its raw matrix is not 6 x 5.

assert( ...
    isfield(M,Phase) && ...
    isstruct(M.(Phase)), ...
    'Missing phase: %s.', ...
    label);


assert( ...
    isfield(M.(Phase),CaseName) && ...
    isstruct(M.(Phase).(CaseName)), ...
    'Missing case: %s.', ...
    label);


assert( ...
    isfield(M.(Phase).(CaseName),Regime) && ...
    isstruct(M.(Phase).(CaseName).(Regime)), ...
    'Missing regime: %s.', ...
    label);


D = ...
    M.(Phase). ...
        (CaseName). ...
        (Regime);


required = ...
    {'RMSE','ASE','RMSSE'};


for k = 1:numel(required)

    f = ...
        required{k};


    assert( ...
        isfield(D,f), ...
        'Missing %s: %s.', ...
        f, ...
        label);


    A = ...
        double( ...
            D.(f));


    A = ...
        selectCurrentMetricMatrix( ...
            A, ...
            M, ...
            Models, ...
            Kernels, ...
            [label ' | ' f]);


    assert( ...
        all( ...
            ~isinf(A), ...
            'all'), ...
        'Infinite %s found: %s.', ...
        f, ...
        label);


    % RMSSE before calibration can legitimately be NaN when a zero
    % variance is present. Preserve it rather than inventing a value.
    if ~strcmp(f,'RMSSE')

        assert( ...
            all( ...
                isfinite(A), ...
                'all'), ...
            'Nonfinite %s found: %s.', ...
            f, ...
            label);

    end


    D.(f) = ...
        A;

end

end


% =========================================================================
function Aout = ...
    selectCurrentMetricMatrix( ...
        A, ...
        Source, ...
        Models, ...
        Kernels, ...
        label)
%SELECTCURRENTMETRICMATRIX
%
% Normalize a saved metric matrix to the CURRENT manuscript order.
%
% Preferred method:
%   use Source.Models / Source.Kernels labels.
%
% Fallback:
%   accept exact current size, or its transpose.
%
% No unlabeled row/column is silently dropped.

nModel = ...
    numel(Models);


nKernel = ...
    numel(Kernels);


sourceModels = ...
    {};


sourceKernels = ...
    {};


if isfield(Source,'Models') && ...
   ~isempty(Source.Models)

    sourceModels = ...
        cellstr( ...
            string( ...
                Source.Models(:)));

end


if isfield(Source,'Kernels') && ...
   ~isempty(Source.Kernels)

    sourceKernels = ...
        cellstr( ...
            string( ...
                Source.Kernels(:)));

end


% -------------------------------------------------------------------------
% Best case: source labels exist and explain the matrix dimensions.
% -------------------------------------------------------------------------

if ~isempty(sourceModels) && ...
   ~isempty(sourceKernels)

    if isequal( ...
            size(A), ...
            [numel(sourceModels) numel(sourceKernels)])

        % already source-model x source-kernel

    elseif isequal( ...
            size(A), ...
            [numel(sourceKernels) numel(sourceModels)])

        A = ...
            A.';

    else

        % If metadata is stale but the numeric matrix is already exactly
        % the current manuscript size, use it directly.
        if isequal(size(A),[nModel nKernel])

            Aout = ...
                A;

            return

        elseif isequal(size(A),[nKernel nModel])

            Aout = ...
                A.';

            return

        end


        error( ...
            ['Metric matrix size does not match its stored labels:\n%s\n' ...
             'Matrix size        = %d x %d\n' ...
             'Stored model count = %d\n' ...
             'Stored kernel count= %d\n' ...
             'Current target     = %d x %d'], ...
            label, ...
            size(A,1), ...
            size(A,2), ...
            numel(sourceModels), ...
            numel(sourceKernels), ...
            nModel, ...
            nKernel);

    end


    rowIdx = ...
        zeros( ...
            1, ...
            nModel);


    colIdx = ...
        zeros( ...
            1, ...
            nKernel);


    for i = 1:nModel

        q = ...
            find( ...
                strcmpi( ...
                    strtrim(string(sourceModels)), ...
                    Models{i}), ...
                1);


        assert( ...
            ~isempty(q), ...
            'Current model "%s" not found in saved source: %s.', ...
            Models{i}, ...
            label);


        rowIdx(i) = ...
            q;

    end


    for j = 1:nKernel

        q = ...
            find( ...
                strcmpi( ...
                    strtrim(string(sourceKernels)), ...
                    Kernels{j}), ...
                1);


        assert( ...
            ~isempty(q), ...
            'Current kernel "%s" not found in saved source: %s.', ...
            Kernels{j}, ...
            label);


        colIdx(j) = ...
            q;

    end


    Aout = ...
        A( ...
            rowIdx, ...
            colIdx);


    assert( ...
        isequal( ...
            size(Aout), ...
            [nModel nKernel]), ...
        'Current metric selection failed: %s.', ...
        label);


    return

end


% -------------------------------------------------------------------------
% No labels: only safe exact-size normalization is allowed.
% -------------------------------------------------------------------------

if isequal(size(A),[nModel nKernel])

    Aout = ...
        A;


elseif isequal(size(A),[nKernel nModel])

    Aout = ...
        A.';


else

    error( ...
        ['Unlabeled metric matrix has incompatible size:\n%s\n' ...
         'Found    = %d x %d\n' ...
         'Expected = %d x %d\n\n' ...
         'No row/column is dropped without source labels.'], ...
        label, ...
        size(A,1), ...
        size(A,2), ...
        nModel, ...
        nKernel);

end

end


