% =========================================================================
function s = ...
    latexNum( ...
        x)

if isnan(x)

    s = ...
        '--';

    return

end


if isinf(x)

    if x > 0

        s = ...
            '$\infty$';

    else

        s = ...
            '$-\infty$';

    end

    return

end


if x == 0

    s = ...
        '$0$';

    return

end


ax = ...
    abs(x);


if ax >= 1e4 || ...
   ax < 1e-3

    exponent = ...
        floor( ...
            log10(ax));


    mantissa = ...
        x / ...
        10^exponent;


    s = ...
        sprintf( ...
            '$%.4f\\times10^{%d}$', ...
            mantissa, ...
            exponent);

else

    s = ...
        sprintf( ...
            '$%.6g$', ...
            x);

end

end


