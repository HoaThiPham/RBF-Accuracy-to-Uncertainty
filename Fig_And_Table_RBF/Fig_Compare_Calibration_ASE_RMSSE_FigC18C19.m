% =========================================================================
function addModelSeparators( ...
    ax, ...
    nRows)

% 5 kernels per model.  Boundaries:
%   5.5, 10.5, 15.5, 20.5, 25.5

for x = 5.5:5:(nRows-0.5)

    xline( ...
        ax, ...
        x, ...
        ':', ...
        'HandleVisibility','off');

end

end


% =========================================================================
function setConfigurationTicks( ...
    ax, ...
    D, ...
    showLabels)

n = ...
    height(D);


set( ...
    ax, ...
    'XTick', ...
    1:n);


if showLabels

    labels = ...
        string(D.ModelCode) + ...
        "-" + ...
        string(D.KernelCode);


    set( ...
        ax, ...
        'XTickLabel', ...
        cellstr(labels), ...
        'XTickLabelRotation',90, ...
        'FontSize',7);

else

    set( ...
        ax, ...
        'XTickLabel',[]);

end

end


