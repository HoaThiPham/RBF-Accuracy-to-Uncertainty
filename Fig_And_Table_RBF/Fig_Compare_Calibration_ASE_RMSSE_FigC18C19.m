    table();


SheetMap = ...
    struct();


for ic = 1:numel(Cases)

    CaseName = ...
        Cases{ic};


    for ir = 1:numel(Regimes)

        Regime = ...
            Regimes{ir};


        for ip = 1:numel(Phases)

            Phase = ...
                Phases{ip};


            label = ...
                sprintf( ...
                    '%s | %s | %s', ...
                    CaseName, ...
                    Regime, ...
                    Phase);


            fprintf('Building %s ...\n',label);


            BeforeBlock = ...
                getMetricBlock( ...
                    Before, ...
                    Phase, ...
                    CaseName, ...
                    Regime, ...
                    Models, ...
                    Kernels, ...
                    ['BEFORE ' label]);


            AfterBlock = ...
                getMetricBlock( ...
                    After, ...
                    Phase, ...
                    CaseName, ...
                    Regime, ...
                    Models, ...
                    Kernels, ...
                    ['AFTER ' label]);


            % -------------------------------------------------------------
            % RMSE consistency: calibration must not alter point prediction.
            % -------------------------------------------------------------

            rmseScale = ...
                max( ...
                    1, ...
                    max( ...
                        abs( ...
                            [ ...
                            BeforeBlock.RMSE(:); ...
                            AfterBlock.RMSE(:) ...
                            ])));


            rmseTol = ...
                1e-10 * ...
                rmseScale;


            maxRMSEDifference = ...
                max( ...
                    abs( ...
                        BeforeBlock.RMSE(:) - ...
                        AfterBlock.RMSE(:)));


            assert( ...
                maxRMSEDifference <= rmseTol, ...
                ['RMSE changed between before/after calibration:\n%s\n' ...
                 'max difference = %.16g\n' ...
                 'tolerance      = %.16g'], ...
                label, ...
                maxRMSEDifference, ...
                rmseTol);


            % -------------------------------------------------------------
            % Derived calibration diagnostics.
            % -------------------------------------------------------------

            RMSE = ...
                AfterBlock.RMSE;


            ASE_Before = ...
                BeforeBlock.ASE;


            ASE_After = ...
                AfterBlock.ASE;


            % -------------------------------------------------------------
            % Normalized ASE diagnostic used in the calibration objective:
            %
            %   ASE / RMSE, ideal target = 1
            %
            % and its absolute distance from the target:
            %
            %   |ASE/RMSE - 1|
            % -------------------------------------------------------------

            ASERatio_Before = ...
                ASE_Before ./ ...
                RMSE;


            ASERatio_After = ...
                ASE_After ./ ...
                RMSE;


            AbsASERatioDev_Before = ...
                abs( ...
                    ASERatio_Before - ...
                    1);


            AbsASERatioDev_After = ...
                abs( ...
                    ASERatio_After - ...
                    1);


            ASERatioImprovement = ...
                AbsASERatioDev_Before - ...
                AbsASERatioDev_After;


            % Retain the dimensional ASE-RMSE quantities for reference,
            % but do NOT use them as the principal calibration criterion.
            ASEminusRMSE_Before = ...
                ASE_Before - ...
                RMSE;


            ASEminusRMSE_After = ...
                ASE_After - ...
                RMSE;


            AbsASEGap_Before = ...
                abs( ...
                    ASEminusRMSE_Before);


            AbsASEGap_After = ...
                abs( ...
                    ASEminusRMSE_After);


            ASEGapImprovement = ...
                AbsASEGap_Before - ...
                AbsASEGap_After;


            RMSSE_Before = ...
                BeforeBlock.RMSSE;


            RMSSE_After = ...
                AfterBlock.RMSSE;


            RMSSEminus1_Before = ...
                RMSSE_Before - ...
                1;


            RMSSEminus1_After = ...
                RMSSE_After - ...
                1;


            AbsRMSSEDev_Before = ...
                abs( ...
                    RMSSEminus1_Before);


            AbsRMSSEDev_After = ...
                abs( ...
                    RMSSEminus1_After);


            RMSSEImprovement = ...
                AbsRMSSEDev_Before - ...
                AbsRMSSEDev_After;


            % -------------------------------------------------------------
            % Detailed 30-row table.
            %
            % Row order:
            %   EGM2008: G M T C L
            %   ggmplus: G M T C L
            %   ...
            % -------------------------------------------------------------

            Detail = ...
                makeDetailTable( ...
                    Models, ...
                    ModelShort, ...
                    Kernels, ...
                    KernelShort, ...
                    RMSE, ...
                    ASE_Before, ...
                    ASE_After, ...
                    ASERatio_Before, ...
                    ASERatio_After, ...
                    AbsASERatioDev_Before, ...
                    AbsASERatioDev_After, ...
                    ASERatioImprovement, ...
                    ASEminusRMSE_Before, ...
                    ASEminusRMSE_After, ...
                    AbsASEGap_Before, ...
                    AbsASEGap_After, ...
                    ASEGapImprovement, ...
                    RMSSE_Before, ...
                    RMSSE_After, ...
                    RMSSEminus1_Before, ...
                    RMSSEminus1_After, ...
                    AbsRMSSEDev_Before, ...
                    AbsRMSSEDev_After, ...
                    RMSSEImprovement);


            Comparison.(Phase). ...
                (CaseName). ...
                (Regime).Detail = ...
                Detail;


            Comparison.(Phase). ...
                (CaseName). ...
                (Regime).MaxRMSEDifference = ...
                maxRMSEDifference;


            % -------------------------------------------------------------
            % One summary row for this 30-configuration block.
            % -------------------------------------------------------------

            SummaryOne = ...
                makeSummaryRow( ...
                    CaseName, ...
                    Regime, ...
                    Phase, ...
                    Detail, ...
                    maxRMSEDifference);


            SummaryRows = ...
                [ ...
                SummaryRows; ...
                SummaryOne ...
                ]; %#ok<AGROW>


            % -------------------------------------------------------------
            % Excel sheet name.
