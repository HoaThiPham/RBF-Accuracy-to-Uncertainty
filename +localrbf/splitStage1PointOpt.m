function S2 = copyExistingFields(S,fieldList)
%COPYEXISTINGFIELDS Copy listed fields that exist.

S2 = ...
    struct();


if isempty(fieldList)
    return
end


for k = 1:numel(fieldList)

    f = ...
        fieldList{k};


    if isfield(S,f)

        S2.(f) = ...
            S.(f);

    end

end

end


% =============================================================
% Local helper
% =============================================================

function S2 = removeFieldsIfPresent(S,fieldList)
%REMOVEFIELDSIFPRESENT Remove only fields that actually exist.

S2 = ...
    S;


if isempty(fieldList) || ...
   ~isstruct(S2)

    return

end


existing = ...
    intersect( ...
        fieldList, ...
        fieldnames(S2), ...
        'stable');


if ~isempty(existing)

    S2 = ...
        rmfield( ...
            S2, ...
            existing);

end

end


