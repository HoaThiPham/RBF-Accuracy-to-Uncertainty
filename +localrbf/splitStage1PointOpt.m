function [Core,Diag,TraceSearch,TraceOpt,TraceNumeric] = ...
    splitStage1PointOpt(PointOpt,saveTrace)
%SPLITSTAGE1POINTOPT Split one Stage-1 PointOpt into storage components.
%
% Optional saveTrace (default true): false suppresses all three TRACE
% outputs while preserving CORE and DIAG. TRACE payloads are also gated by
% nargout, so an output that the caller does not request is not constructed.
%
% This function is STORAGE-ONLY. It does not modify optimization,
% neighborhood construction, radius selection, RNG, or numerical results.
%
% Outputs
% -------
% Core
%   Authoritative compact PointOpt used later by Stage 2.
%   It preserves the complete PointOpt structure and every radius-level
%   field EXCEPT the heavy Radius(j).optimization object, which is cleared.
%
% Diag
%   Compact point/radius diagnostic summaries for routine analysis.
%
% TraceSearch
%   Search metadata and the non-trace portion of each optimizer result,
%   including the complete searchInfo structure.
%
% TraceOpt
%   Complete scientific parameter-evaluation trace except numerical-solver
%   trace fields moved to TraceNumeric. Includes bestEvaluationIndex.
%
% TraceNumeric
%   Numerical/solver evaluation traces such as cond_reg and solver_used.
%
% Exact-neighborhood reuse
% ------------------------
% optimizeAtPointForAllCandidateRadii can reuse an earlier successful
% optimization when two consecutive radii have exactly the same fitting
% indices. The current PointOpt duplicates the full optimization structure
% at the reused radius. To save memory/disk, the split trace files store
% the full trace only at the ORIGINAL source radius. Reused radii retain a
% deterministic sourceRadiusIndex. With saveTrace=true, detailed TRACE
% information is preserved without duplication. With saveTrace=false,
% detailed TRACE is intentionally not retained.
%
% Reconstruction rule for a reused radius:
%
%   source = Trace*.Radius(j).sourceRadiusIndex;
%
% and the source radius contains the complete optimizer information.
%
% bestEvaluationIndex
% -------------------
% This is the index, in the COMPLETE optimizer evaluation order, of the
% first finite minimum-AE evaluation. This matches MATLAB MIN first-tie
% semantics used by optimizeParameters when selecting the best evaluation.

% =============================================================
% 0. Optional TRACE storage control
% =============================================================

if nargin < 2 || isempty(saveTrace)

    saveTrace = ...
        true;

end


if ~(isscalar(saveTrace) && ...
     (islogical(saveTrace) || ...
      (isnumeric(saveTrace) && ...
       isreal(saveTrace) && ...
       isfinite(saveTrace) && ...
       any(saveTrace == [0 1]))))

    error( ...
        'saveTrace must be true/false (or numeric 1/0).');

end


saveTrace = ...
    logical(saveTrace);


% Construct only TRACE outputs that the caller actually requests.
% LocalRBFTraining requests all five outputs when TRACE is enabled and
% only CORE+DIAG when TRACE is disabled. This nargout gate also protects
% direct/legacy calls from constructing large unused TRACE payloads.
wantTraceSearch = ...
    saveTrace && ...
    nargout >= 3;


wantTraceOpt = ...
    saveTrace && ...
    nargout >= 4;


wantTraceNumeric = ...
    saveTrace && ...
    nargout >= 5;


traceComplete = ...
    wantTraceSearch && ...
    wantTraceOpt && ...
    wantTraceNumeric;


% =============================================================
% 1. Validate input
% =============================================================

if ~isstruct(PointOpt) || ...
   ~isscalar(PointOpt)

    error( ...
        'PointOpt must be a scalar structure.');

end


requiredFields = { ...
    'radii', ...
    'nRadii', ...
    'Radius'};


for k = 1:numel(requiredFields)

    if ~isfield( ...
            PointOpt, ...
            requiredFields{k})

        error( ...
            'PointOpt is missing required field "%s".', ...
            requiredFields{k});

    end

end


if ~isnumeric(PointOpt.nRadii) || ...
   ~isscalar(PointOpt.nRadii) || ...
   ~isreal(PointOpt.nRadii) || ...
   ~isfinite(PointOpt.nRadii) || ...
   PointOpt.nRadii < 0 || ...
   PointOpt.nRadii ~= round(PointOpt.nRadii)

    error( ...
        'PointOpt.nRadii must be a finite nonnegative integer.');

end


M = ...
    PointOpt.nRadii;


if numel(PointOpt.radii) ~= M || ...
   numel(PointOpt.Radius) ~= M

    error( ...
        ['PointOpt.radii, PointOpt.nRadii, and PointOpt.Radius ' ...
         'must have consistent lengths.']);

end


% =============================================================
% 2. CORE
%
% Preserve the complete authoritative PointOpt layout needed by
% selectBestRadiusWithToleranceAtEachRadiusCapOverAllCaps.
%
% Only the heavy optimizer object is detached.
% =============================================================

Core = ...
    PointOpt;


for j = 1:M

    if isfield( ...
            Core.Radius(j), ...
            'optimization')

        Core.Radius(j).optimization = ...
            [];

    end

end


Core.storageSplitVersion = ...
    2;


Core.storageRole = ...
    'Stage-1 CORE; authoritative Stage-2 PointOpt';


% =============================================================
% 3. Initialize DIAG / TRACE outputs
% =============================================================

Diag = ...
    makePointHeader( ...
        PointOpt, ...
        'DIAG');


TraceSearch = ...
    [];


TraceOpt = ...
    [];


TraceNumeric = ...
    [];


Diag.Radius = ...
    repmat( ...
        emptyDiagRadius(), ...
        M,1);


if wantTraceSearch

    TraceSearch = ...
        makePointHeader( ...
            PointOpt, ...
            'TRACE_SEARCH');


    TraceSearch.Radius = ...
        repmat( ...
            emptyTraceSearchRadius(), ...
            M,1);

end


if wantTraceOpt

    TraceOpt = ...
        makePointHeader( ...
            PointOpt, ...
            'TRACE_OPT');


    TraceOpt.Radius = ...
        repmat( ...
            emptyTraceOptRadius(), ...
            M,1);

end


if wantTraceNumeric

    TraceNumeric = ...
        makePointHeader( ...
            PointOpt, ...
            'TRACE_NUMERIC');


    TraceNumeric.Radius = ...
        repmat( ...
            emptyTraceNumericRadius(), ...
            M,1);

end


% =============================================================
% 4. Point-level compact diagnostics
% =============================================================

Diag.PointSummary = ...
    copyExistingFields( ...
        PointOpt, ...
        { ...
        'success', ...
        'message', ...
        'nValidRadii', ...
        'nFailedRadii', ...
        'nNeighborhoodFailures', ...
        'nPolynomialFailures', ...
        'nGeometryFailures', ...
        'nOptimizationFailures', ...
        'nUniqueNeighborhoodOptimizations', ...
        'nReusedRadii', ...
        'nEvaluations', ...
        'nGAEvaluations', ...
        'nFallbackEvaluations', ...
        'nGridEvaluations', ...
        'nRefinementEvaluations', ...
        'nValidEvaluations', ...
        'nFailedEvaluations', ...
        'nRBFSolves', ...
        'distanceWallTime', ...
        'distanceLookupWallTime', ...
        'totalWallTime' ...
        });


% =============================================================
% 5. Split every radius
% =============================================================

for j = 1:M

    Rj = ...
        PointOpt.Radius(j);


    % ---------------------------------------------------------
    % 5.1 Resolve exact-neighborhood trace source
    % ---------------------------------------------------------

    [isReused,sourceRadiusIndex] = ...
        resolveTraceSource( ...
            Rj, ...
            j, ...
            M);


    % ---------------------------------------------------------
    % 5.2 DIAG
    % ---------------------------------------------------------

    Dj = ...
        emptyDiagRadius();


    Dj.radiusIndex = ...
        getFieldOrDefault( ...
            Rj, ...
            'radiusIndex', ...
            j);


    Dj.radius = ...
        getFieldOrDefault( ...
            Rj, ...
            'radius', ...
            NaN);


    Dj.success = ...
        logicalScalarOrDefault( ...
            Rj, ...
            'success', ...
            false);


    Dj.failureStage = ...
        textFieldOrDefault( ...
            Rj, ...
            'failureStage', ...
            '');


    Dj.message = ...
        textFieldOrDefault( ...
            Rj, ...
            'message', ...
            '');


    Dj.neighborhoodSuccess = ...
        logicalScalarOrDefault( ...
            Rj, ...
            'neighborhoodSuccess', ...
            false);


    Dj.neighbor_count = ...
        numericScalarOrDefault( ...
            Rj, ...
            'neighbor_count', ...
            NaN);


    Dj.nAvailable = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nAvailable', ...
            NaN);


    Dj.nWithinRadius = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nWithinRadius', ...
            NaN);


    Dj.nAddedForMinimum = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nAddedForMinimum', ...
            NaN);


    Dj.usedMinNeighborFallback = ...
        logicalScalarOrDefault( ...
            Rj, ...
            'usedMinNeighborFallback', ...
            false);


    Dj.requestedRadius = ...
        numericScalarOrDefault( ...
            Rj, ...
            'requestedRadius', ...
            NaN);


    Dj.effectiveRadius = ...
        numericScalarOrDefault( ...
            Rj, ...
            'effectiveRadius', ...
            NaN);


    Dj.selectedMaxDistance = ...
        numericScalarOrDefault( ...
            Rj, ...
            'selectedMaxDistance', ...
            NaN);


    Dj.polynomialAdmissible = ...
        logicalScalarOrDefault( ...
            Rj, ...
            'polynomialAdmissible', ...
            false);


    Dj.d_local = ...
        numericScalarOrDefault( ...
            Rj, ...
            'd_local', ...
            NaN);


    Dj.optimizationSuccess = ...
        logicalScalarOrDefault( ...
            Rj, ...
            'optimizationSuccess', ...
            false);


    Dj.optimizationReused = ...
        isReused;


    Dj.sourceRadiusIndex = ...
        sourceRadiusIndex;


    Dj.C_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'C_best', ...
            NaN);


    Dj.reg_param_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'reg_param_best', ...
            NaN);


    Dj.epsilon_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'epsilon_best', ...
            NaN);


    Dj.AE_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'AE_best', ...
            NaN);


    Dj.yhat_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'yhat_best', ...
            NaN);


    Dj.y_diff_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'y_diff_best', ...
            NaN);


    Dj.cond_reg_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'cond_reg_best', ...
            NaN);


    Dj.rel_residual_best = ...
        numericScalarOrDefault( ...
            Rj, ...
            'rel_residual_best', ...
            NaN);


    Dj.solver_used_best = ...
        textFieldOrDefault( ...
            Rj, ...
            'solver_used_best', ...
            '');


    Dj.nEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nEvaluations', ...
            0);


    Dj.nGAEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nGAEvaluations', ...
            0);


    Dj.nFallbackEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nFallbackEvaluations', ...
            0);


    Dj.nGridEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nGridEvaluations', ...
            0);


    Dj.nRefinementEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nRefinementEvaluations', ...
            0);


    Dj.nValidEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nValidEvaluations', ...
            0);


    Dj.nFailedEvaluations = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nFailedEvaluations', ...
            0);


    Dj.nRBFSolves = ...
        numericScalarOrDefault( ...
            Rj, ...
            'nRBFSolves', ...
            0);


    Dj.neighborhoodWallTime = ...
        numericScalarOrDefault( ...
            Rj, ...
            'neighborhoodWallTime', ...
            0);


    Dj.admissibilityWallTime = ...
        numericScalarOrDefault( ...
            Rj, ...
            'admissibilityWallTime', ...
            0);


    Dj.geometryWallTime = ...
        numericScalarOrDefault( ...
            Rj, ...
            'geometryWallTime', ...
            0);


    Dj.optimizationWallTime = ...
        numericScalarOrDefault( ...
            Rj, ...
            'optimizationWallTime', ...
            0);


    Dj.totalWallTime = ...
        numericScalarOrDefault( ...
            Rj, ...
            'totalWallTime', ...
            0);


    % ---------------------------------------------------------
    % SearchInfo summary used frequently in diagnostics.
    % Complete searchInfo is retained in TRACE_SEARCH.
    % ---------------------------------------------------------

    Opt = ...
        getOptimization( ...
            Rj);


    if ~isempty(Opt) && ...
       isfield(Opt,'searchInfo') && ...
       isstruct(Opt.searchInfo) && ...
       isscalar(Opt.searchInfo)

        SI = ...
            Opt.searchInfo;


        Dj.searchInfoSummary = ...
            copyExistingFields( ...
                SI, ...
                { ...
                'requestedMethod', ...
                'method', ...
                'nGrid', ...
                'success', ...
                'converged', ...
                'usedFallback', ...
                'fallbackSucceeded', ...
                'gridSucceeded', ...
                'refinementSucceeded', ...
                'refinementSource', ...
                'exitflag', ...
                'generations', ...
                'funccount', ...
                'gaConverged', ...
                'acceptedLimitStop', ...
                'gaBestAE', ...
                'searchBestAE', ...
                'finalAE', ...
                'finalSearchAEDifference', ...
                'searchConsistent', ...
                'nEvaluations', ...
                'nGAEvaluations', ...
                'nFallbackEvaluations', ...
                'nGridEvaluations', ...
                'nRefinementEvaluations', ...
                'nValidEvaluations', ...
                'nFailedEvaluations', ...
                'nRBFSolvesSearch', ...
                'nRBFSolvesFinal', ...
                'nRBFSolves', ...
                'gaWallTime', ...
                'fallbackWallTime', ...
                'gridWallTime', ...
                'refinementWallTime', ...
                'finalWallTime', ...
                'totalWallTime', ...
                'boundaryTolerance', ...
                'CRelativePosition', ...
                'CNearLowerBound', ...
                'CNearUpperBound', ...
                'RegRelativePosition', ...
                'RegNearLowerBound', ...
                'RegNearUpperBound', ...
                'message', ...
                'gaMessage', ...
                'firstFailureMessage' ...
                });

    end


    Diag.Radius(j) = ...
        Dj;


    % ---------------------------------------------------------
    % TRACE OFF: CORE + DIAG are complete for this radius.
    % Do not construct/copy any optimizer trace payload.
    % ---------------------------------------------------------

    if ~wantTraceSearch

        continue

    end


    % ---------------------------------------------------------
    % 5.3 Trace provenance metadata
    % ---------------------------------------------------------

    if wantTraceSearch

        TraceSearch.Radius(j).radiusIndex = ...
            j;


        TraceSearch.Radius(j).radius = ...
            Dj.radius;


        TraceSearch.Radius(j).optimizationReused = ...
            isReused;


        TraceSearch.Radius(j).sourceRadiusIndex = ...
            sourceRadiusIndex;

    end


    if wantTraceOpt

        TraceOpt.Radius(j).radiusIndex = ...
            j;


        TraceOpt.Radius(j).radius = ...
            Dj.radius;


        TraceOpt.Radius(j).optimizationReused = ...
            isReused;


        TraceOpt.Radius(j).sourceRadiusIndex = ...
            sourceRadiusIndex;

    end


    if wantTraceNumeric

        TraceNumeric.Radius(j).radiusIndex = ...
            j;


        TraceNumeric.Radius(j).radius = ...
            Dj.radius;


        TraceNumeric.Radius(j).optimizationReused = ...
            isReused;


        TraceNumeric.Radius(j).sourceRadiusIndex = ...
            sourceRadiusIndex;

    end


    % ---------------------------------------------------------
    % For a reused radius, do NOT duplicate the original large trace.
    % The complete trace is recoverable through sourceRadiusIndex.
    % ---------------------------------------------------------

    if isReused

        if wantTraceSearch

            TraceSearch.Radius(j).traceStored = ...
                false;

        end


        if wantTraceOpt

            TraceOpt.Radius(j).traceStored = ...
                false;


            % Preserve best-evaluation provenance for convenient access.
            if sourceRadiusIndex >= 1 && ...
               sourceRadiusIndex < j

                TraceOpt.Radius(j).bestEvaluationIndex = ...
                    TraceOpt.Radius( ...
                        sourceRadiusIndex).bestEvaluationIndex;


                TraceOpt.Radius(j).bestStage = ...
                    TraceOpt.Radius( ...
                        sourceRadiusIndex).bestStage;


                TraceOpt.Radius(j).bestC = ...
                    TraceOpt.Radius( ...
                        sourceRadiusIndex).bestC;


                TraceOpt.Radius(j).bestRegParam = ...
                    TraceOpt.Radius( ...
                        sourceRadiusIndex).bestRegParam;


                TraceOpt.Radius(j).bestObjective = ...
                    TraceOpt.Radius( ...
                        sourceRadiusIndex).bestObjective;

            end

        end



        if wantTraceNumeric

            TraceNumeric.Radius(j).traceStored = ...
                false;

        end


        continue

    end


    % ---------------------------------------------------------
    % 5.4 Non-reused radius with no optimizer object
    % ---------------------------------------------------------

    if isempty(Opt)

        continue

    end


    if wantTraceSearch

        TraceSearch.Radius(j).traceStored = ...
            true;

    end


    if wantTraceOpt

        TraceOpt.Radius(j).traceStored = ...
            true;

    end


    if wantTraceNumeric

        TraceNumeric.Radius(j).traceStored = ...
            true;

    end


    % ---------------------------------------------------------
    % 5.5 TRACE_SEARCH
    %
    % Preserve ALL optimizer top-level fields except trace/searchInfo
    % as optimizationCore. Preserve searchInfo exactly.
    % ---------------------------------------------------------

    if wantTraceSearch

        TraceSearch.Radius(j).optimizationFieldOrder = ...
            fieldnames(Opt);


        TraceSearch.Radius(j).optimizationCore = ...
            removeFieldsIfPresent( ...
                Opt, ...
                {'trace','searchInfo'});


        if isfield(Opt,'searchInfo')

            TraceSearch.Radius(j).searchInfo = ...
                Opt.searchInfo;

        end

    end


    % ---------------------------------------------------------
    % 5.6 TRACE_OPT / TRACE_NUMERIC
    %
    % Preserve every trace field exactly once:
    %   numeric/solver-specific fields -> TRACE_NUMERIC
    %   all remaining trace fields      -> TRACE_OPT
    % ---------------------------------------------------------

    if (wantTraceOpt || wantTraceNumeric) && ...
       isfield(Opt,'trace') && ...
       isstruct(Opt.trace) && ...
       isscalar(Opt.trace)

        FullTrace = ...
            Opt.trace;


        numericTraceFields = ...
            intersect( ...
                {'cond_reg','solver_used'}, ...
                fieldnames(FullTrace), ...
                'stable');


        if wantTraceNumeric

            TraceNumeric.Radius(j).trace = ...
                copyExistingFields( ...
                    FullTrace, ...
                    numericTraceFields);

        end


        if wantTraceOpt

            TraceOpt.Radius(j).traceFieldOrder = ...
                fieldnames(FullTrace);


            TraceOpt.Radius(j).trace = ...
                removeFieldsIfPresent( ...
                    FullTrace, ...
                    numericTraceFields);


            [bestIndex,bestStage,bestC,bestReg,bestObjective] = ...
                findBestEvaluation( ...
                    FullTrace);


            TraceOpt.Radius(j).bestEvaluationIndex = ...
                bestIndex;


            TraceOpt.Radius(j).bestStage = ...
                bestStage;


            TraceOpt.Radius(j).bestC = ...
                bestC;


            TraceOpt.Radius(j).bestRegParam = ...
                bestReg;


            TraceOpt.Radius(j).bestObjective = ...
                bestObjective;

        end

    end



    % ---------------------------------------------------------
    % 5.7 Final selected numerical result convenience fields
    % ---------------------------------------------------------

    if wantTraceNumeric

        TraceNumeric.Radius(j).final = ...
            copyExistingFields( ...
                Opt, ...
                { ...
                'cond_reg', ...
                'rel_residual', ...
                'solver_used' ...
                });

    end

end


% =============================================================
% 6. Cross-part integrity metadata
% =============================================================

Core.traceSaved = ...
    traceComplete;


Core.traceRequested = ...
    saveTrace;


if traceComplete

    Core.traceLayout = ...
        'TRACE_SEARCH + TRACE_OPT + TRACE_NUMERIC';

elseif ~saveTrace

    Core.traceLayout = ...
        'TRACE disabled; CORE + DIAG only';

else

    Core.traceLayout = ...
        'Partial TRACE outputs requested by caller; not checkpoint-complete';

end



Diag.storageSplitVersion = ...
    2;


Diag.traceSaved = ...
    traceComplete;


Diag.traceRequested = ...
    saveTrace;



reusePolicy = ...
    'Store full trace only at original exact-neighborhood source radius';


if wantTraceSearch

    TraceSearch.storageSplitVersion = ...
        2;


    TraceSearch.reusePolicy = ...
        reusePolicy;

end


if wantTraceOpt

    TraceOpt.storageSplitVersion = ...
        2;


    TraceOpt.reusePolicy = ...
        reusePolicy;

end


if wantTraceNumeric

    TraceNumeric.storageSplitVersion = ...
        2;


    TraceNumeric.reusePolicy = ...
        reusePolicy;

end

end


