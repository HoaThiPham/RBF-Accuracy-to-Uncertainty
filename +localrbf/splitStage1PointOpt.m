% =============================================================
% Local helper
% =============================================================

function [isReused,sourceRadiusIndex] = resolveTraceSource(Rj,j,M)
%RESOLVETRACESOURCE Validate exact-neighborhood reuse provenance.

isReused = ...
    logicalScalarOrDefault( ...
        Rj, ...
        'optimizationReused', ...
        false);


if ~isReused

    sourceRadiusIndex = ...
        j;

    return

end


sourceRadiusIndex = ...
    numericScalarOrDefault( ...
        Rj, ...
        'reusedFromRadiusIndex', ...
        NaN);


if ~isfinite(sourceRadiusIndex) || ...
   sourceRadiusIndex ~= round(sourceRadiusIndex) || ...
   sourceRadiusIndex < 1 || ...
   sourceRadiusIndex > M || ...
   sourceRadiusIndex >= j

    error( ...
        ['Radius %d is marked optimizationReused but has invalid ' ...
         'reusedFromRadiusIndex.'], ...
        j);

end

end


% =============================================================
% Local helper
% =============================================================

function [bestIndex,bestStage,bestC,bestReg,bestObjective] = ...
    findBestEvaluation(T)
%FINDBESTEVALUATION First finite minimum-AE evaluation.

bestIndex = ...
    NaN;


bestStage = ...
    NaN;


bestC = ...
    NaN;


bestReg = ...
    NaN;


bestObjective = ...
    NaN;


if ~isstruct(T) || ...
   ~isscalar(T) || ...
   ~isfield(T,'AE') || ...
   ~isnumeric(T.AE) || ...
   isempty(T.AE)

    return

end


AE = ...
    T.AE(:);


valid = ...
    isfinite(AE);


if ~any(valid)

    return

end


validIdx = ...
    find(valid);


[bestObjective,kBest] = ...
    min( ...
        AE(validIdx));


bestIndex = ...
    validIdx(kBest);


if isfield(T,'stage') && ...
   numel(T.stage) >= bestIndex

    bestStage = ...
        T.stage(bestIndex);

end


if isfield(T,'C') && ...
   numel(T.C) >= bestIndex

    bestC = ...
        T.C(bestIndex);

end


if isfield(T,'RegParam') && ...
   numel(T.RegParam) >= bestIndex

    bestReg = ...
        T.RegParam(bestIndex);

end

end


